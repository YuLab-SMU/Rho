import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const defaultOutput = path.join(
  repositoryRoot,
  "desktop/ui/src/transport/generated/runtime-output.ts",
);

function option(name) {
  const index = process.argv.indexOf(name);
  return index < 0 ? null : process.argv[index + 1] ?? null;
}

function transform(raw) {
  const upstreamHeader = "// This file has been generated by Tauri Specta. Do not edit this file manually.";
  const identifiedHeader = `// Generated by tauri-specta 2.0.0-rc.25 with specta-typescript 0.0.12. Do not edit.
// Rust sources: rho-store/runtime_output + rho-desktop/runtime_registry.`;
  const sourceImport = 'import { invoke as __TAURI_INVOKE, Channel } from "@tauri-apps/api/core";';
  const targetImport = `import type { Channel } from "@tauri-apps/api/core";

export type RuntimeOutputInvoke = <T>(
	command: string,
	args?: Record<string, unknown>,
) => Promise<T>;`;
  const commandStart = "export const commands = {";
  const typeMarker = "\n\n/* Types */";
  if (!raw.startsWith(upstreamHeader) || !raw.includes(sourceImport) || !raw.includes(commandStart) || !raw.includes(typeMarker)) {
    throw new Error("tauri-specta output shape changed; review the generator adapter before accepting it");
  }
  const imported = raw
    .replace(upstreamHeader, identifiedHeader)
    .replace(sourceImport, targetImport);
  const start = imported.indexOf(commandStart);
  const end = imported.indexOf(typeMarker, start);
  const commandBlock = imported.slice(start, end);
  if (!commandBlock.endsWith("};")) {
    throw new Error("tauri-specta command block no longer has the expected terminator");
  }
  const factoryBlock = commandBlock
    .replace(commandStart, "export const createRuntimeOutputCommands = (__TAURI_INVOKE: RuntimeOutputInvoke) => ({")
    .replace(/};$/, "});");
  return `${imported.slice(0, start)}${factoryBlock}${imported.slice(end)}`.replace(/\n+$/u, "\n");
}

function generate() {
  const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "rho-runtime-output-bindings-"));
  const rawPath = path.join(temporaryDirectory, "runtime-output.raw.ts");
  try {
    execFileSync(
      "cargo",
      [
        "test",
        "-p",
        "rho-desktop",
        "runtime_output_typescript_export",
        "--locked",
        "--",
        "--ignored",
      ],
      {
        cwd: repositoryRoot,
        env: { ...process.env, RHO_RUNTIME_OUTPUT_BINDINGS_PATH: rawPath },
        stdio: ["ignore", "inherit", "inherit"],
      },
    );
    return transform(fs.readFileSync(rawPath, "utf8"));
  } finally {
    fs.rmSync(temporaryDirectory, { recursive: true, force: true });
  }
}

const requestedOutput = option("--output");
const outputPath = requestedOutput == null ? defaultOutput : path.resolve(process.cwd(), requestedOutput);
const generated = generate();

if (process.argv.includes("--check")) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== generated) {
    throw new Error(`Runtime Output bindings are stale: ${path.relative(repositoryRoot, outputPath)}`);
  }
  console.log(`Runtime Output bindings are current: ${path.relative(repositoryRoot, outputPath)}`);
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, generated);
  console.log(`Generated ${path.relative(repositoryRoot, outputPath)}`);
}
