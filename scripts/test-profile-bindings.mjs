import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generator = path.join(repositoryRoot, "scripts/generate-profile-bindings.mjs");
const generatedPath = path.join(repositoryRoot, "desktop/ui/src/transport/generated/profile.ts");
const commandNames = [
  "ui_profile_snapshot",
  "ui_profile_set_mode",
  "ui_profile_select_scene",
  "ui_profile_select_page",
  "ui_profile_page_apply",
  "ui_profile_page_export",
  "ui_profile_scene_duplicate",
  "ui_profile_scene_save",
  "ui_profile_scene_rename",
  "ui_profile_scene_delete",
  "ui_profile_scene_reset",
];

function count(text, needle) {
  return text.split(needle).length - 1;
}

function generate(outputPath, check = false) {
  const args = [generator, "--output", outputPath];
  if (check) args.push("--check");
  execFileSync(process.execPath, args, {
    cwd: repositoryRoot,
    stdio: ["ignore", "ignore", "pipe"],
  });
}

const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "rho-profile-bindings-test-"));
try {
  const first = path.join(temporaryDirectory, "first.ts");
  const second = path.join(temporaryDirectory, "second.ts");
  generate(first);
  generate(second);
  const firstBytes = fs.readFileSync(first);
  assert.deepEqual(firstBytes, fs.readFileSync(second), "two clean Profile generations differ");
  assert.deepEqual(firstBytes, fs.readFileSync(generatedPath), "checked-in Profile bindings are stale");

  fs.appendFileSync(first, "// stale fixture\n");
  assert.throws(
    () => generate(first, true),
    /Command failed/,
    "a one-byte Profile binding drift must fail freshness validation",
  );

  const generated = fs.readFileSync(generatedPath, "utf8");
  const tauri = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/tauri.ts"), "utf8");
  const types = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/types.ts"), "utf8");
  const facet = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/profile.ts"), "utf8");
  const mock = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/mock.ts"), "utf8");

  assert.match(generated, /Generated by tauri-specta 2\.0\.0-rc\.25 with specta-typescript 0\.0\.12/);
  assert.match(generated, /Rust sources: rho-ui-contract\/profile\+vibe \+ rho-desktop\/ui_profile/);
  assert.match(generated, /import type \{ ResourceBindingV1 \} from "\.\/resource"/);
  assert.match(generated, /import type \{ SceneStateV1, SurfaceOriginV1 \} from "\.\/surface-studio"/);
  assert.doesNotMatch(generated, /export type (?:ResourceBindingV1|SceneStateV1|SurfaceOriginV1) =/);
  assert.match(facet, /export interface ProfileTransport/);
  assert.match(facet, /createTauriProfileTransport/);
  assert.match(facet, /unsupported contract version/);
  assert.match(tauri, /\.\.\.createTauriProfileTransport\(invoke\)/);

  for (const command of commandNames) {
    assert.equal(count(generated, `"${command}"`), 1, `${command} must be generated exactly once`);
    assert.equal(count(tauri, `"${command}"`), 0, `${command} must not remain handwritten`);
  }
  for (const typeName of [
    "ProjectUiProfile",
    "ProjectUiProfileSnapshot",
    "SurfaceInstanceSpec",
    "UiProfileRevisionRequest",
    "UiProfileSetModeRequest",
    "UiProfileSelectSceneRequest",
    "UiProfileSelectPageRequest",
    "UiProfileSceneLabelRequest",
    "UiProfileSceneTargetRequest",
    "VibePage",
    "VibePageMutation",
    "VibePageMutationRequest",
    "VibePageExportRequest",
    "VibePageExport",
  ]) {
    assert.doesNotMatch(
      types,
      new RegExp(`export (?:interface|type) ${typeName}\\b`),
      `${typeName} must not remain a handwritten wire DTO in types.ts`,
    );
  }
  for (const generatedType of [
    "ProjectUiProfileSnapshotV1",
    "ProjectUiProfileV1",
    "SurfaceInstanceSpecV1",
    "UiProfileRevisionRequestV1",
    "VibePageV1",
    "VibePageMutationV1",
    "VibePageExportV1",
  ]) {
    assert.match(generated, new RegExp(`export type ${generatedType}\\b`));
  }
  for (const method of [
    "loadUiProfile",
    "setUiProfileMode",
    "selectUiProfileScene",
    "selectUiProfilePage",
    "applyVibePage",
    "exportVibePage",
    "duplicateUiProfileScene",
    "saveUiProfileScene",
    "renameUiProfileScene",
    "deleteUiProfileScene",
    "resetUiProfileScene",
  ]) {
    assert.match(facet, new RegExp(`\\b${method}\\b`));
    assert.match(mock, new RegExp(`\\b${method}\\b`));
  }
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });
}

console.log("Profile and Vibe generated binding contract passed");
