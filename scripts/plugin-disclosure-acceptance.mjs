// Discover real owner entries and a two-Skill/two-view independent package in
// Chrome. No Agent, scientific runtime or Core Host is needed for disclosure.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { chromium } from '@playwright/test';
import { RhoService } from '../dist/server.js';
import { RhoClient } from '../dist/client.js';
import { pluginCli } from '../dist/plugin-cli.js';
import { inspectPage } from './browser-checks.mjs';

const evidence = path.resolve(process.env.RHO_PLUGIN_EVIDENCE ?? 'work/plugin-disclosure/after');
await fs.mkdir(evidence, { recursive: true });
const root = await fs.mkdtemp('/tmp/rho-disclosure-');
const report = { passed: false, checks: [], widths: [], errors: [] };
let service, reduced, browser, page;
const done = text => { report.checks.push(text); console.log('ok · ' + text); };
try {
  const source = path.join(root, 'package');
  await pluginCli(['create', source, '--id', 'disclosure-example']);
  const packageFile = path.join(source, 'package.json'), pkg = JSON.parse(await fs.readFile(packageFile, 'utf8'));
  pkg.files.push('second-skill.md', 'second-view.html');
  await fs.writeFile(packageFile, JSON.stringify(pkg));
  const manifest = JSON.parse(await fs.readFile(path.join(source, 'rho-plugin.json'), 'utf8'));
  manifest.title = 'Discovery example';
  manifest.skills[0].title = 'First guide';
  manifest.skills.push({ id: 'second', title: 'Second guide', file: 'second-skill.md' });
  manifest.views[0].title = 'First view';
  manifest.views.push({ id: 'second', title: 'Second view', file: 'second-view.html' });
  await fs.writeFile(path.join(source, manifest.skills[0].file), '# First guide\nRead the first instructions.');
  await fs.writeFile(path.join(source, 'second-skill.md'), '# Second guide\nRead the second instructions. 研究指导 🧬');
  // Each fixture view is a small page of its own, as a real package's would be.
  const viewPage = (title, lead) => `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${title}</title><style>body{margin:0;padding:22px;font:14px/1.5 -apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif;color:#202927}h1{margin:0 0 6px;font-size:17px}p{margin:0;color:#68736f}</style></head><body><h1>${title}</h1><p>${lead}</p></body></html>`;
  await fs.writeFile(path.join(source, manifest.views[0].file), viewPage('First plugin view', 'A page the package ships, shown in a frame of its own. 第一个视图'));
  await fs.writeFile(path.join(source, 'second-view.html'), viewPage('Second plugin view', 'A second page of the same package.'));
  await fs.writeFile(path.join(source, 'rho-plugin.json'), JSON.stringify(manifest));
  await fs.writeFile(path.join(source, 'host.mjs'), `import fs from 'node:fs'; export function run(_, input, ctx) { fs.writeFileSync(ctx.projectRoot + '/HOST-INVOKED', 'unexpected'); return input; }`);
  service = await new RhoService({ root, stateDir: path.join(root, 'state'), coreBinary: '/missing', rscript: '/missing', example: false }).start();
  const admin = new RhoClient({ url: service.url, token: service.adminToken });
  const project = await admin.call('project.create', { name: 'Plugin discovery' });
  await admin.call('extension.install', { source });
  const catalog = await admin.call('capability.list', { projectId: project.id });
  report.owners = catalog.plugins.map(p => ({ id: p.id, packageVersion: p.packageVersion, skills: p.listing.skills.length, views: p.listing.views.length, operations: p.listing.operations.length }));
  browser = await chromium.launch({ executablePath: process.env.RHO_UI_CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  report.browser = browser.version();
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  page = await context.newPage(); page.setDefaultTimeout(15000);
  page.on('pageerror', e => report.errors.push(e.message));
  const navigate = async () => {
    await page.goto(service.url + '/#project=' + project.id);
    await page.reload();
    await page.locator('.project-nav').getByRole('button', { name: 'Plugins', exact: true }).click();
    await page.locator('#plugin-search').waitFor();
  };
  const search = text => page.getByRole('searchbox', { name: 'Find a plugin or capability' }).fill(text);
  const card = title => page.locator('.plugin-card').filter({ has: page.getByText(title, { exact: true }) });
  const back = () => page.locator('main').getByRole('button', { name: 'All plugins', exact: true }).click();
  await navigate();
  assert.equal(await page.locator('.plugin-card').count(), 12);
  await page.screenshot({ path: path.join(evidence, 'catalog-1440.png') });
  await search('data flow'); assert.equal(await page.locator('.plugin-card').count(), 1);
  await card('Notebook').click();
  assert.equal(await page.locator('.plugin-views .plugin-entry-name').count(), 6);
  await page.screenshot({ path: path.join(evidence, 'notebook-1440.png') });
  done('search finds a plugin through a specialized view and exposes all six Notebook views');
  const sessionSkill = page.locator('.plugin-skill').filter({ has: page.getByText('kernel.session', { exact: true }) });
  await page.route('**/api/v2/skill.read', route => route.fulfill({ status: 409, json: { apiVersion: '2.0', ok: false, error: { kind: 'unavailable', message: 'Skill temporarily unavailable.', details: {} } } }));
  await sessionSkill.getByRole('button', { name: 'Read skill', exact: true }).click();
  await sessionSkill.getByRole('alert').waitFor();
  await page.screenshot({ path: path.join(evidence, 'skill-read-failure.png') });
  await page.unroute('**/api/v2/skill.read');
  await sessionSkill.getByRole('button', { name: 'Try again', exact: true }).click();
  await sessionSkill.locator('.plugin-skill-text').waitFor();
  assert.equal(await sessionSkill.locator('.plugin-skill-text').textContent(), catalog.skills.find(s => s.id === 'kernel.session').content);
  await sessionSkill.getByText('Requirements and provenance', { exact: true }).click();
  await page.screenshot({ path: path.join(evidence, 'skill-read-recovered.png') });
  done('Skill read failure is visible and retry reads the exact digest-bound owner instructions');
  await back(); await search('Markdown'); await card('Documents').click();
  assert.ok((await page.locator('.plugin-views').innerText()).includes('@rho-workspace/plugin-markdown'));
  assert.ok((await page.locator('.plugin-views').innerText()).includes('@rho-workspace/plugin-html'));
  await page.locator('.plugin-native > summary').click();
  assert.match(await page.locator('.plugin-native').innerText(), /PreToolUse/);
  assert.match(await page.locator('.plugin-native').innerText(), /documents\.workspace/);
  await page.locator('.plugin-mcp > summary').click();
  await page.locator('.plugin-mcp .plugin-entry-details > summary').click();
  for (const name of ['rho_index', 'rho_resolve', 'rho_call', 'rho_read']) assert.ok((await page.locator('.plugin-mcp').innerText()).includes(name));
  const readContract = page.locator('.plugin-operation').filter({ has: page.getByText('document.read', { exact: true }) });
  await readContract.locator(':scope > summary').click();
  assert.match(await readContract.locator('pre').first().textContent(), /documentId/);
  await page.screenshot({ path: path.join(evidence, 'mcp-contract-1440.png') });
  done('Documents discloses its two UI extension packages, native Skill, edit hook and shared MCP contracts');
  for (const width of [1440, 1024, 768, 390]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.getByRole('navigation', { name: 'Plugin entries' }).getByRole('button', { name: /^Views/ }).click();
    const finding = await inspectPage(page); assert.equal(finding.overflow, false); assert.deepEqual(finding.unnamed, []);
    report.widths.push(finding);
    await page.screenshot({ path: path.join(evidence, `documents-${width}.png`) });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await back(); await search('rho.analysis-run');
  const workspaceSkill = page.locator('.plugin-workspace-skills .plugin-skill');
  assert.equal(await workspaceSkill.count(), 1);
  await workspaceSkill.getByRole('button', { name: 'Read skill', exact: true }).click();
  await workspaceSkill.locator('.plugin-skill-text').waitFor();
  assert.equal(await workspaceSkill.locator('.plugin-skill-text').textContent(), catalog.skills.find(s => s.id === 'rho.analysis-run').content);
  await page.screenshot({ path: path.join(evidence, 'workspace-skill.png') });
  done('application Skills are discoverable with their own Rho ownership, separate from plugin and project Skills');
  await search('Second guide');
  const extension = page.locator('.extension-list > article'); assert.equal(await extension.count(), 1);
  await extension.getByRole('button', { name: 'Read Second guide', exact: true }).click();
  await extension.locator('.extension-guide pre').filter({ hasText: 'Read the second instructions.' }).waitFor();
  assert.match(await extension.locator('.extension-guide pre').textContent(), /研究指导 🧬/);
  await extension.getByRole('button', { name: 'Read First guide', exact: true }).click();
  await extension.locator('.extension-guide pre').filter({ hasText: 'Read the first instructions.' }).waitFor();
  await extension.getByRole('button', { name: 'Open Second view', exact: true }).click();
  await page.frameLocator('.extension-view iframe').getByRole('heading', { name: 'Second plugin view' }).waitFor();
  await extension.getByRole('button', { name: 'Open First view', exact: true }).click();
  await page.frameLocator('.extension-view iframe').getByRole('heading', { name: 'First plugin view' }).waitFor();
  await extension.locator('.extension-operations > summary').click();
  await extension.scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(evidence, 'independent-entries-1440.png') });
  await page.setViewportSize({ width: 390, height: 1000 });
  assert.equal((await inspectPage(page)).overflow, false);
  await extension.getByRole('button', { name: 'Read Second guide', exact: true }).click();
  await extension.locator('.extension-guide pre').filter({ hasText: 'Read the second instructions.' }).waitFor();
  await extension.locator('.extension-guide').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(evidence, 'independent-skill-390.png') });
  done('an independent package exposes both Skills, both live HTML views and every declared operation');
  assert.equal((await admin.call('kernel.read', { projectId: project.id, limit: 1 })).sessions.length, 0);
  assert.equal((await admin.call('action.list', { projectId: project.id })).length, 0);
  assert.equal(service.bridge.owned.size, 0);
  await assert.rejects(fs.access(path.join(project.root, 'HOST-INVOKED')), { code: 'ENOENT' });
  await admin.call('capability.configure', { projectId: project.id, expectedVersion: 0, changeId: 'disable-notebook', enabled: service.plugins.availableIds().filter(id => id !== 'kernel') });
  await page.setViewportSize({ width: 1440, height: 1000 }); await navigate();
  await card('Notebook').click();
  assert.match(await page.locator('.plugin-notice').innerText(), /Off in Plugin discovery/);
  assert.equal(await page.locator('.plugin-views .plugin-entry-name').count(), 6);
  assert.equal(await page.getByRole('button', { name: 'Read skill', exact: true }).isDisabled(), true);
  await page.screenshot({ path: path.join(evidence, 'disabled-notebook.png') });
  done('turning a plugin off retains its descriptive inventory and refuses Skill reading');
  const reducedRoot = path.join(root, 'reduced'); await fs.mkdir(reducedRoot);
  reduced = await new RhoService({ root: reducedRoot, stateDir: path.join(root, 'reduced-state'), plugins: ['documents', 'files'], coreBinary: '/missing', rscript: '/missing', example: false }).start();
  const other = new RhoClient({ url: reduced.url, token: reduced.adminToken });
  const otherProject = await other.call('project.create', { name: 'Reduced installation' });
  await page.goto(reduced.url + '/#project=' + otherProject.id);
  await page.locator('.project-nav').getByRole('button', { name: 'Plugins', exact: true }).click();
  await card('Notebook').click();
  assert.equal(await page.locator('.plugin-views .plugin-entry-name').count(), 6);
  assert.equal(await page.getByRole('button', { name: 'Read skill', exact: true }).isDisabled(), true);
  assert.equal(reduced.plugins.optional('kernel'), undefined); assert.equal(reduced.plugins.optional('skills'), undefined);
  await page.screenshot({ path: path.join(evidence, 'unselected-notebook.png') });
  done('an unselected Notebook keeps its full build inventory without importing its owner');
  assert.deepEqual(report.errors, []);
  report.passed = true;
} catch (error) {
  report.failure = error.stack;
  await page?.screenshot({ path: path.join(evidence, 'failure.png') }).catch(() => {});
  throw error;
} finally {
  await browser?.close(); await reduced?.close(); await service?.close();
  await fs.rm(root, { recursive: true, force: true });
  await fs.writeFile(path.join(evidence, 'report.json'), JSON.stringify(report, null, 2) + '\n');
}
console.log(JSON.stringify({ passed: report.passed, evidence }));
