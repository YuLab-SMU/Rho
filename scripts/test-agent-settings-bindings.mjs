import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generator = path.join(repositoryRoot, "scripts/generate-agent-settings-bindings.mjs");
const generatedPath = path.join(
  repositoryRoot,
  "desktop/ui/src/transport/generated/agent-settings.ts",
);
const commandNames = [
  "agent_llm_declare_model_capability",
  "agent_llm_delete_model",
  "agent_llm_discover_models",
  "agent_llm_save_model",
  "agent_llm_settings",
  "agent_llm_set_context_capacity",
  "agent_llm_set_credential",
  "agent_llm_select_model",
  "agent_llm_test_model",
  "agent_llm_view_credential",
];

function count(text, needle) {
  return text.split(needle).length - 1;
}

function generate(outputPath, check = false) {
  const args = [generator, "--output", outputPath];
  if (check) args.push("--check");
  execFileSync(process.execPath, args, {
    cwd: repositoryRoot,
    stdio: ["ignore", "ignore", "pipe"],
  });
}

const temporaryDirectory = fs.mkdtempSync(
  path.join(os.tmpdir(), "rho-agent-settings-bindings-test-"),
);
try {
  const first = path.join(temporaryDirectory, "first.ts");
  const second = path.join(temporaryDirectory, "second.ts");
  generate(first);
  generate(second);
  const firstBytes = fs.readFileSync(first);
  assert.deepEqual(firstBytes, fs.readFileSync(second), "two clean Agent settings generations differ");
  assert.deepEqual(firstBytes, fs.readFileSync(generatedPath), "checked-in Agent settings bindings are stale");

  fs.appendFileSync(first, "// stale fixture\n");
  assert.throws(
    () => generate(first, true),
    /Command failed/,
    "a one-byte Agent settings binding drift must fail freshness validation",
  );

  const generated = fs.readFileSync(generatedPath, "utf8");
  const tauri = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/tauri.ts"), "utf8");
  const types = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/types.ts"), "utf8");
  const facet = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/agent-settings.ts"), "utf8");
  const mock = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/mock.ts"), "utf8");
  const rust = fs.readFileSync(
    path.join(repositoryRoot, "desktop/src-tauri/src/commands/agent_llm.rs"),
    "utf8",
  );

  assert.match(generated, /Generated by tauri-specta 2\.0\.0-rc\.25 with specta-typescript 0\.0\.12/);
  assert.match(generated, /Rust sources: rho-desktop\/agent_llm service \+ commands\/agent_llm facade/);
  assert.match(generated, /agentLlmSettings: \(\) =>/);
  assert.match(generated, /agentLlmDeclareModelCapability: \(request: AgentModelCapabilityDeclarationRequest\)/);
  assert.match(generated, /agentLlmDeleteModel: \(request: DeleteModelRequest\)/);
  assert.match(generated, /agentLlmDiscoverModels: \(providerId: string\)/);
  assert.match(generated, /agentLlmSaveModel: \(model: AgentModelProfile\)/);
  assert.match(generated, /agentLlmSetContextCapacity: \(request: AgentContextCapacityRequest\)/);
  assert.match(generated, /agentLlmSetCredential: \(providerId: string, credential: string, confirmReplace: boolean\)/);
  assert.match(generated, /agentLlmSelectModel: \(request: AgentLlmSelectRequest\)/);
  assert.match(generated, /agentLlmTestModel: \(modelId: string\)/);
  assert.match(generated, /agentLlmViewCredential: \(request: AgentLlmCredentialRevealRequest\)/);
  assert.match(
    generated,
    /export type AgentLlmCredentialRevealView = \{\s*outcome: AgentLlmCredentialRevealOutcome,\s*credential: string \| null,?\s*\}/,
  );
  assert.match(generated, /"revealed" \| "credential_missing" \| "store_unavailable" \| "source_ineligible"/);
  assert.equal(
    count(generated, "credential: string | null"),
    1,
    "only the credential reveal view may carry a value field",
  );
  assert.doesNotMatch(generated, /expectedRevision[\s\S]{0,200}agent_llm_view_credential/);
  assert.doesNotMatch(generated, /credential_value|credentialValue|revealed_secret|revealedSecret/);
  assert.match(generated, /export type AgentProviderProfileView = \{[\s\S]*?\} & AgentProviderProfile/);
  assert.match(generated, /export type AgentModelProfileView = \{[\s\S]*?\} & AgentModelProfile/);
  assert.match(generated, /context_window_tokens: number/);
  assert.match(generated, /reserved_output_tokens: number/);
  assert.match(generated, /credential_status: string/);
  assert.doesNotMatch(generated, /\n\tapi_key: string/);
  assert.match(facet, /export interface AgentSettingsTransport/);
  assert.match(facet, /createTauriAgentSettingsTransport/);
  assert.match(tauri, /\.\.\.createTauriAgentSettingsTransport\(invoke\)/);

  for (const command of commandNames) {
    assert.equal(count(generated, `"${command}"`), 1, `${command} must be generated exactly once`);
    assert.equal(count(tauri, `"${command}"`), 0, `${command} must not remain handwritten`);
  }
  for (const typeName of ["AgentModelContextCapacity", "AgentLlmSettingsView", "AgentContextCapacityRequest"]) {
    assert.doesNotMatch(
      types,
      new RegExp(`export (?:interface|type) ${typeName}\\b`),
      `${typeName} must not remain a handwritten wire DTO in types.ts`,
    );
    assert.match(facet, new RegExp(`export type ${typeName}\\b`));
  }
  for (const method of [
    "loadAgentLlmSettings",
    "discoverProviderModels",
    "setAgentContextCapacity",
    "saveProviderCredential",
    "selectAgentChatModel",
    "testProviderModel",
    "viewProviderCredential",
    "saveModel",
    "deleteModel",
    "setModelContextCapacity",
    "declareModelCapability",
  ]) {
    assert.match(facet, new RegExp(`\\b${method}\\b`));
    assert.match(mock, new RegExp(`\\b${method}\\b`));
  }
  assert.match(rust, /async fn agent_llm_settings\([\s\S]{0,400}?\) -> Result<AgentLlmSettingsView, String>/);
  assert.match(rust, /async fn agent_llm_declare_model_capability\([\s\S]{0,500}?\) -> Result<AgentLlmSettingsView, String>/);
  assert.match(rust, /async fn agent_llm_delete_model\([\s\S]{0,500}?\) -> Result<AgentLlmSettingsView, String>/);
  assert.match(rust, /async fn agent_llm_discover_models\([\s\S]{0,700}?\) -> Result<AgentModelDiscoveryResponse, String>/);
  assert.match(rust, /async fn agent_llm_save_model\([\s\S]{0,500}?\) -> Result<AgentLlmSettingsView, String>/);
  assert.match(rust, /async fn agent_llm_set_context_capacity\([\s\S]{0,500}?\) -> Result<AgentLlmSettingsView, String>/);
  assert.match(rust, /async fn agent_llm_set_credential\([\s\S]{0,700}?\) -> Result<AgentLlmSettingsView, String>/);
  assert.match(rust, /async fn agent_llm_select_model\([\s\S]{0,500}?\) -> Result<AgentLlmSettingsView, String>/);
  assert.match(rust, /async fn agent_llm_test_model\([\s\S]{0,900}?\) -> Result<AgentLlmSettingsView, String>/);
  assert.match(rust, /async fn agent_llm_view_credential\([\s\S]{0,1200}?\) -> Result<AgentLlmCredentialRevealView, String>/);
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });
}

console.log("Agent settings and capacity generated binding contract passed");
