import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generator = path.join(repositoryRoot, "scripts/generate-agent-turn-bindings.mjs");
const generatedPath = path.join(
  repositoryRoot,
  "desktop/ui/src/transport/generated/agent-turn.ts",
);

function count(text, needle) {
  return text.split(needle).length - 1;
}

function generate(outputPath, check = false) {
  const args = [generator, "--output", outputPath];
  if (check) args.push("--check");
  execFileSync(process.execPath, args, {
    cwd: repositoryRoot,
    stdio: ["ignore", "ignore", "pipe"],
  });
}

const temporaryDirectory = fs.mkdtempSync(
  path.join(os.tmpdir(), "rho-agent-turn-bindings-test-"),
);
try {
  const first = path.join(temporaryDirectory, "first.ts");
  const second = path.join(temporaryDirectory, "second.ts");
  generate(first);
  generate(second);
  const firstBytes = fs.readFileSync(first);
  assert.deepEqual(
    firstBytes,
    fs.readFileSync(second),
    "two clean Agent turn detail generations differ",
  );
  assert.deepEqual(
    firstBytes,
    fs.readFileSync(generatedPath),
    "checked-in Agent turn detail bindings are stale",
  );

  fs.appendFileSync(first, "// stale fixture\n");
  assert.throws(
    () => generate(first, true),
    /Command failed/,
    "a one-byte Agent turn detail binding drift must fail freshness validation",
  );

  const generated = fs.readFileSync(generatedPath, "utf8");
  const tauri = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/tauri.ts"), "utf8");
  const types = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/types.ts"), "utf8");
  const facet = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/agent-turn.ts"), "utf8");
  const mock = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/mock.ts"), "utf8");

  assert.match(generated, /Generated by tauri-specta 2\.0\.0-rc\.25 with specta-typescript 0\.0\.12/);
  assert.match(generated, /Rust sources: rho-store\/agent \+ rho-desktop\/commands\/agent_execution/);
  assert.equal(count(generated, '"get_agent_turn_detail"'), 1);
  assert.equal(count(tauri, '"get_agent_turn_detail"'), 0);
  assert.match(generated, /import type \{ AgentTurnSummary \} from "\.\/agent-conversation"/);
  assert.equal(count(generated, "export type AgentTurnSummary"), 0);
  assert.match(generated, /getAgentTurnDetail: \(turnId: string\)/);
  assert.doesNotMatch(generated, /ApprovalRequest|AgentTurnContextItem|context_items/);
  assert.match(facet, /export interface AgentTurnDetailTransport/);
  assert.match(facet, /createTauriAgentTurnDetailTransport/);
  assert.match(facet, /checkedAgentTurnSummary/);
  assert.match(tauri, /\.\.\.createTauriAgentTurnDetailTransport\(invoke\)/);
  assert.match(mock, /\bgetAgentTurnDetail\b/);

  for (const typeName of [
    "AgentTurnEvent",
    "AgentTurnDetail",
  ]) {
    assert.doesNotMatch(
      types,
      new RegExp(`export (?:interface|type) ${typeName}\\b`),
      `${typeName} must not remain a handwritten wire DTO in types.ts`,
    );
    assert.match(facet, new RegExp(`export type ${typeName}\\b`));
  }
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });
}

console.log("Agent turn detail generated binding contract passed");
