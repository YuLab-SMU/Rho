import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generator = path.join(repositoryRoot, "scripts/generate-runtime-output-bindings.mjs");
const generatedPath = path.join(
  repositoryRoot,
  "desktop/ui/src/transport/generated/runtime-output.ts",
);
const commandNames = [
  "runtime_execution_get",
  "runtime_execution_list",
  "runtime_output_search",
  "runtime_output_policy_get",
  "runtime_output_policy_update",
  "runtime_output_page",
  "runtime_output_reference",
  "runtime_output_prune",
  "runtime_execution_delete",
  "runtime_output_follow",
];

function count(text, needle) {
  return text.split(needle).length - 1;
}

function generate(outputPath, check = false) {
  const args = [generator, "--output", outputPath];
  if (check) args.push("--check");
  execFileSync(process.execPath, args, {
    cwd: repositoryRoot,
    stdio: ["ignore", "ignore", "pipe"],
  });
}

const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "rho-runtime-output-test-"));
try {
  const first = path.join(temporaryDirectory, "first.ts");
  const second = path.join(temporaryDirectory, "second.ts");
  generate(first);
  generate(second);
  const firstBytes = fs.readFileSync(first);
  const secondBytes = fs.readFileSync(second);
  assert.deepEqual(firstBytes, secondBytes, "two clean Runtime Output generations differ");
  assert.deepEqual(
    firstBytes,
    fs.readFileSync(generatedPath),
    "checked-in Runtime Output bindings are stale",
  );

  fs.appendFileSync(first, "// stale fixture\n");
  assert.throws(
    () => generate(first, true),
    /Command failed/,
    "a one-byte generated binding drift must fail freshness validation",
  );

  const generated = fs.readFileSync(generatedPath, "utf8");
  const tauri = fs.readFileSync(
    path.join(repositoryRoot, "desktop/ui/src/transport/tauri.ts"),
    "utf8",
  );
  const types = fs.readFileSync(
    path.join(repositoryRoot, "desktop/ui/src/transport/types.ts"),
    "utf8",
  );
  const facet = fs.readFileSync(
    path.join(repositoryRoot, "desktop/ui/src/transport/runtime-output.ts"),
    "utf8",
  );
  const mock = fs.readFileSync(
    path.join(repositoryRoot, "desktop/ui/src/transport/mock.ts"),
    "utf8",
  );

  assert.match(generated, /Generated by tauri-specta 2\.0\.0-rc\.25 with specta-typescript 0\.0\.12/);
  assert.match(generated, /Rust sources: rho-store\/runtime_output \+ rho-desktop\/runtime_registry/);
  assert.match(generated, /createRuntimeOutputCommands/);
  assert.match(generated, /Channel<RuntimeOutputFollowFrame>/);
  assert.match(facet, /export interface RuntimeOutputTransport/);
  assert.match(facet, /createTauriRuntimeOutputTransport/);
  assert.match(tauri, /\.\.\.createTauriRuntimeOutputTransport\(invoke\)/);
  for (const command of commandNames) {
    assert.equal(count(generated, `"${command}"`), 1, `${command} must be generated exactly once`);
    assert.equal(count(tauri, `"${command}"`), 0, `${command} must not remain handwritten in tauri.ts`);
  }
  for (const typeName of [
    "RuntimeExecution",
    "RuntimeOutputChunk",
    "RuntimeOutputPage",
    "RuntimeOutputFollowFrame",
    "RuntimeOutputSearchResult",
    "RuntimeOutputPolicy",
    "RuntimeOutputReference",
  ]) {
    assert.doesNotMatch(
      types,
      new RegExp(`export (?:interface|type) ${typeName}\\b`),
      `${typeName} must not remain a handwritten wire DTO in types.ts`,
    );
    assert.match(generated, new RegExp(`export type ${typeName}\\b`));
  }
  for (const method of [
    "getRuntimeExecution",
    "listRuntimeExecutions",
    "loadRuntimeOutputPage",
    "searchRuntimeOutput",
    "getRuntimeOutputPolicy",
    "updateRuntimeOutputPolicy",
    "createRuntimeOutputReference",
    "pruneRuntimeOutput",
    "deleteRuntimeExecution",
    "followRuntimeOutput",
  ]) {
    assert.match(facet, new RegExp(`\\b${method}\\b`));
    assert.match(mock, new RegExp(`\\b${method}\\b`));
  }
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });
}

console.log("Runtime Output generated binding contract passed");
