import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generator = path.join(repositoryRoot, "scripts/generate-surface-studio-bindings.mjs");
const generatedPath = path.join(
  repositoryRoot,
  "desktop/ui/src/transport/generated/surface-studio.ts",
);
const commandNames = [
  "surface_list",
  "surface_open",
  "surface_update",
  "surface_close",
  "surface_suspend",
  "surface_resume",
  "studio_scene",
  "studio_apply",
  "studio_undo",
  "studio_redo",
  "runtime_attach",
  "runtime_detach",
];

function count(text, needle) {
  return text.split(needle).length - 1;
}

function generate(outputPath, check = false) {
  const args = [generator, "--output", outputPath];
  if (check) args.push("--check");
  execFileSync(process.execPath, args, {
    cwd: repositoryRoot,
    stdio: ["ignore", "ignore", "pipe"],
  });
}

const temporaryDirectory = fs.mkdtempSync(
  path.join(os.tmpdir(), "rho-surface-studio-bindings-test-"),
);
try {
  const first = path.join(temporaryDirectory, "first.ts");
  const second = path.join(temporaryDirectory, "second.ts");
  generate(first);
  generate(second);
  const firstBytes = fs.readFileSync(first);
  assert.deepEqual(
    firstBytes,
    fs.readFileSync(second),
    "two clean Surface/Studio generations differ",
  );
  assert.deepEqual(
    firstBytes,
    fs.readFileSync(generatedPath),
    "checked-in Surface/Studio bindings are stale",
  );

  fs.appendFileSync(first, "// stale fixture\n");
  assert.throws(
    () => generate(first, true),
    /Command failed/,
    "a one-byte Surface/Studio binding drift must fail freshness validation",
  );

  const generated = fs.readFileSync(generatedPath, "utf8");
  const tauri = fs.readFileSync(
    path.join(repositoryRoot, "desktop/ui/src/transport/tauri.ts"),
    "utf8",
  );
  const types = fs.readFileSync(
    path.join(repositoryRoot, "desktop/ui/src/transport/types.ts"),
    "utf8",
  );
  const facet = fs.readFileSync(
    path.join(repositoryRoot, "desktop/ui/src/transport/surface-studio.ts"),
    "utf8",
  );
  const mock = fs.readFileSync(
    path.join(repositoryRoot, "desktop/ui/src/transport/mock.ts"),
    "utf8",
  );

  assert.match(
    generated,
    /Generated by tauri-specta 2\.0\.0-rc\.25 with specta-typescript 0\.0\.12/,
  );
  assert.match(
    generated,
    /import type \{ RuntimeBindingV1, RuntimeInstanceRequestV1 \} from "\.\/runtime"/,
  );
  assert.match(generated, /import type \{ ResourceBindingV1 \} from "\.\/resource"/);
  assert.doesNotMatch(generated, /export type ResourceBindingV1 =/);
  assert.doesNotMatch(generated, /export type RuntimeBindingV1 =/);
  assert.doesNotMatch(generated, /export type RuntimeInstanceRequestV1 =/);
  assert.match(facet, /export interface SurfaceStudioTransport/);
  assert.match(facet, /createTauriSurfaceStudioTransport/);
  assert.match(facet, /unsupported contract version/);
  assert.match(tauri, /\.\.\.createTauriSurfaceStudioTransport\(invoke\)/);

  for (const command of commandNames) {
    assert.equal(
      count(generated, `"${command}"`),
      1,
      `${command} must be generated exactly once`,
    );
    assert.equal(
      count(tauri, `"${command}"`),
      0,
      `${command} must not remain handwritten in tauri.ts`,
    );
  }
  for (const typeName of [
    "SurfaceRuntimeSnapshot",
    "OpenSurfaceRequest",
    "SurfaceInstanceRequest",
    "UpdateSurfaceRequest",
    "LayoutNode",
    "SceneEdit",
    "SceneEditRequest",
    "StudioRevisionRequest",
    "StudioRuntimeSnapshot",
    "RuntimeAttachmentRequest",
    "RuntimeDetachRequest",
  ]) {
    assert.doesNotMatch(
      types,
      new RegExp(`export (?:interface|type) ${typeName}\\b`),
      `${typeName} must not remain a handwritten wire DTO in types.ts`,
    );
  }
  for (const generatedType of [
    "SurfaceRuntimeSnapshotV1_Serialize",
    "OpenSurfaceRequestV1",
    "SurfaceInstanceRequestV1",
    "UpdateSurfaceRequestV1",
    "LayoutNodeV1",
    "SceneEditV1",
    "SceneEditRequestV1",
    "StudioRevisionRequestV1",
    "StudioRuntimeSnapshotV1",
    "RuntimeAttachmentRequestV1",
    "RuntimeDetachRequestV1",
  ]) {
    assert.match(generated, new RegExp(`export type ${generatedType}\\b`));
  }
  for (const method of [
    "loadSurfaces",
    "openSurface",
    "updateSurface",
    "closeSurface",
    "suspendSurface",
    "resumeSurface",
    "loadStudio",
    "applyStudio",
    "undoStudio",
    "redoStudio",
    "attachRuntime",
    "detachRuntime",
  ]) {
    assert.match(facet, new RegExp(`\\b${method}\\b`));
    assert.match(mock, new RegExp(`\\b${method}\\b`));
  }
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });
}

console.log("Surface and Studio generated binding contract passed");
