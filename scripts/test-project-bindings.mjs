import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generator = path.join(repositoryRoot, "scripts/generate-project-bindings.mjs");
const generatedPath = path.join(repositoryRoot, "desktop/ui/src/transport/generated/project.ts");
const commandNames = ["project_open", "project_pick_directory", "project_restore_session"];

function count(text, needle) {
  return text.split(needle).length - 1;
}

function generate(outputPath, check = false) {
  const args = [generator, "--output", outputPath];
  if (check) args.push("--check");
  execFileSync(process.execPath, args, {
    cwd: repositoryRoot,
    stdio: ["ignore", "ignore", "pipe"],
  });
}

const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "rho-project-bindings-test-"));
try {
  const first = path.join(temporaryDirectory, "first.ts");
  const second = path.join(temporaryDirectory, "second.ts");
  generate(first);
  generate(second);
  const firstBytes = fs.readFileSync(first);
  assert.deepEqual(firstBytes, fs.readFileSync(second), "two clean Project generations differ");
  assert.deepEqual(firstBytes, fs.readFileSync(generatedPath), "checked-in Project bindings are stale");

  fs.appendFileSync(first, "// stale fixture\n");
  assert.throws(
    () => generate(first, true),
    /Command failed/,
    "a one-byte Project binding drift must fail freshness validation",
  );

  const generated = fs.readFileSync(generatedPath, "utf8");
  const tauri = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/tauri.ts"), "utf8");
  const types = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/types.ts"), "utf8");
  const facet = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/project.ts"), "utf8");
  const mock = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/mock.ts"), "utf8");

  assert.match(generated, /Generated by tauri-specta 2\.0\.0-rc\.25 with specta-typescript 0\.0\.12/);
  assert.match(generated, /Rust sources: rho-desktop\/project transition commands/);
  assert.match(generated, /projectOpen: \(path: string\)/);
  assert.match(generated, /projectPickDirectory: \(\)/);
  assert.match(generated, /projectRestoreSession: \(\)/);
  assert.match(generated, /files: ProjectFile\[\]/);
  assert.match(generated, /session: ProjectSessionSnapshot/);
  assert.match(generated, /blocker: ProjectSwitchBlocker \| null/);
  assert.match(generated, /restart_required: boolean/);
  assert.match(facet, /export interface ProjectTransport/);
  assert.match(facet, /assertProjectSwitchStatus/);
  assert.match(tauri, /\.\.\.createTauriProjectTransport\(projectCommands\)/);

  for (const command of commandNames) {
    assert.equal(count(generated, `"${command}"`), 1, `${command} must be generated exactly once`);
    assert.equal(count(tauri, `"${command}"`), 0, `${command} must not remain handwritten`);
  }
  assert.doesNotMatch(types, /export interface ProjectSwitchResponse\b/);
  assert.doesNotMatch(types, /export type ProjectSwitchStatus\b/);
  for (const method of ["openProject", "pickProjectDirectory"]) {
    assert.match(facet, new RegExp(`\\b${method}\\b`));
    assert.match(mock, new RegExp(`\\b${method}\\b`));
  }
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });
}

console.log("Project transition generated binding contract passed");
