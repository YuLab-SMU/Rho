import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generator = path.join(repositoryRoot, "scripts/generate-plugin-surface-bindings.mjs");
const generatedPath = path.join(
  repositoryRoot,
  "desktop/ui/src/transport/generated/plugin-surface.ts",
);
const commandNames = ["plugin_surface_document", "plugin_surface_event"];

function count(text, needle) {
  return text.split(needle).length - 1;
}

function generate(outputPath, check = false) {
  const args = [generator, "--output", outputPath];
  if (check) args.push("--check");
  execFileSync(process.execPath, args, {
    cwd: repositoryRoot,
    stdio: ["ignore", "ignore", "pipe"],
  });
}

const temporaryDirectory = fs.mkdtempSync(
  path.join(os.tmpdir(), "rho-plugin-surface-bindings-test-"),
);
try {
  const first = path.join(temporaryDirectory, "first.ts");
  const second = path.join(temporaryDirectory, "second.ts");
  generate(first);
  generate(second);
  const firstBytes = fs.readFileSync(first);
  assert.deepEqual(firstBytes, fs.readFileSync(second), "two clean Plugin Surface generations differ");
  assert.deepEqual(firstBytes, fs.readFileSync(generatedPath), "checked-in Plugin Surface bindings are stale");

  fs.appendFileSync(first, "// stale fixture\n");
  assert.throws(
    () => generate(first, true),
    /Command failed/,
    "a one-byte Plugin Surface binding drift must fail freshness validation",
  );

  const generated = fs.readFileSync(generatedPath, "utf8");
  const tauri = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/tauri.ts"), "utf8");
  const types = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/types.ts"), "utf8");
  const facet = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/plugin-surface.ts"), "utf8");
  const mock = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/mock.ts"), "utf8");
  const rust = fs.readFileSync(path.join(repositoryRoot, "desktop/src-tauri/src/plugin_surface_runtime.rs"), "utf8");
  const extensionCargo = fs.readFileSync(path.join(repositoryRoot, "crates/rho-extension-runtime/Cargo.toml"), "utf8");

  assert.match(generated, /Generated by tauri-specta 2\.0\.0-rc\.25 with specta-typescript 0\.0\.12/);
  assert.match(generated, /Rust sources: rho-extension-runtime\/surface\+viewer \+ rho-desktop\/plugin_surface_runtime/);
  assert.match(generated, /import type \{ ProjectId, SurfaceId, SurfaceInstanceId, SurfaceInstanceRequestV1 \} from "\.\/surface-studio"/);
  assert.doesNotMatch(generated, /export type SurfaceInstanceRequestV1\b/);
  assert.match(generated, /pluginSurfaceDocument: \(request: PluginSurfaceDocumentRequest\)/);
  assert.match(generated, /pluginSurfaceEvent: \(request: PluginSurfaceEventRequest\)/);
  assert.match(generated, /export type SurfaceBlockV1 = \{ kind: "row"; blocks: SurfaceBlockV1\[\] \}/);
  assert.match(generated, /\{ kind: "command_button"; control_id: string/);
  assert.match(generated, /export type PluginSurfaceEventStatus = "completed" \| "queued"/);
  assert.match(generated, /command_result: PluginCommandResultV1_Serialize \| null/);
  assert.match(generated, /provenance: PluginSurfaceJsonValue \| null/);
  assert.match(facet, /export interface PluginSurfaceTransport/);
  assert.match(facet, /readonly contract: "rho\.plugin_surface_document\.v1"/);
  assert.match(tauri, /\.\.\.createTauriPluginSurfaceTransport\(invoke\)/);
  assert.match(extensionCargo, /^specta\.workspace = true$/m);

  for (const command of commandNames) {
    assert.equal(count(generated, `"${command}"`), 1, `${command} must be generated exactly once`);
    assert.equal(count(tauri, `"${command}"`), 0, `${command} must not remain handwritten`);
  }
  for (const typeName of [
    "PluginSurfaceBlock",
    "PluginSurfaceDocument",
    "PluginSurfaceDocumentRequest",
    "PluginSurfaceEventRequest",
    "PluginSurfaceDocumentView",
    "PluginSurfaceEventResult",
  ]) {
    assert.doesNotMatch(
      types,
      new RegExp(`export (?:interface|type) ${typeName}\\b`),
      `${typeName} must not remain a handwritten wire DTO in types.ts`,
    );
    assert.match(facet, new RegExp(`export type ${typeName}\\b`));
  }
  for (const method of ["loadPluginSurfaceDocument", "dispatchPluginSurfaceEvent"]) {
    assert.match(facet, new RegExp(`\\b${method}\\b`));
    assert.match(mock, new RegExp(`\\b${method}\\b`));
  }
  assert.match(rust, /pub\(crate\) async fn plugin_surface_document\([\s\S]{0,300}?\) -> Result<PluginSurfaceDocumentView, String>/);
  assert.match(rust, /pub\(crate\) async fn plugin_surface_event\([\s\S]{0,300}?\) -> Result<PluginSurfaceEventResult, String>/);
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });
}

console.log("Workspace-plugin Surface generated binding contract passed");
