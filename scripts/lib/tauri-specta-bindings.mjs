import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const upstreamHeader = "// This file has been generated by Tauri Specta. Do not edit this file manually.";
const sourceImportPattern = /import \{ invoke as __TAURI_INVOKE(, Channel)? \} from "@tauri-apps\/api\/core";/u;

function option(name) {
  const index = process.argv.indexOf(name);
  return index < 0 ? null : process.argv[index + 1] ?? null;
}

function removeTypeDeclaration(source, name, domainLabel) {
  const marker = `export type ${name} = `;
  const start = source.indexOf(marker);
  if (start < 0 || source.indexOf(marker, start + marker.length) >= 0) {
    throw new Error(`${domainLabel} expected exactly one generated ${name} declaration`);
  }
  const end = source.indexOf("\n\n", start);
  if (end < 0 || !source.slice(start, end).endsWith(";")) {
    throw new Error(`${domainLabel} generated ${name} declaration shape changed`);
  }
  return `${source.slice(0, start)}${source.slice(end + 2)}`;
}

function transform(raw, config) {
  const commandStart = "export const commands = {";
  const typeMarker = "\n\n/* Types */";
  const importMatch = raw.match(sourceImportPattern);
  if (
    !raw.startsWith(upstreamHeader) ||
    importMatch == null ||
    !raw.includes(commandStart) ||
    !raw.includes(typeMarker)
  ) {
    throw new Error(`${config.domainLabel} tauri-specta output shape changed; review the shared adapter`);
  }

  const externalByPath = new Map();
  for (const external of config.externalTypes ?? []) {
    const names = externalByPath.get(external.from) ?? [];
    names.push(external.name);
    externalByPath.set(external.from, names);
  }
  const externalImports = [...externalByPath.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([from, names]) => `import type { ${names.sort().join(", ")} } from "${from}";`);
  const channelImport = importMatch[1] == null
    ? []
    : ['import type { Channel } from "@tauri-apps/api/core";'];
  const targetImport = [
    ...channelImport,
    ...externalImports,
    "",
    `export type ${config.invokeTypeName} = <T>(`,
    "\tcommand: string,",
    "\targs?: Record<string, unknown>,",
    ") => Promise<T>;",
  ].join("\n");
  const identifiedHeader = `// Generated by tauri-specta 2.0.0-rc.25 with specta-typescript 0.0.12. Do not edit.
// Rust sources: ${config.rustSources}.`;
  let imported = raw
    .replace(upstreamHeader, identifiedHeader)
    .replace(sourceImportPattern, targetImport);

  const start = imported.indexOf(commandStart);
  const end = imported.indexOf(typeMarker, start);
  const commandBlock = imported.slice(start, end);
  if (!commandBlock.endsWith("};")) {
    throw new Error(`${config.domainLabel} tauri-specta command block shape changed`);
  }
  const factoryBlock = commandBlock
    .replace(
      commandStart,
      `export const ${config.factoryName} = (__TAURI_INVOKE: ${config.invokeTypeName}) => ({`,
    )
    .replace(/};$/, "});");
  imported = `${imported.slice(0, start)}${factoryBlock}${imported.slice(end)}`;
  for (const external of config.externalTypes ?? []) {
    imported = removeTypeDeclaration(imported, external.name, config.domainLabel);
  }
  for (const omitted of config.omitTypes ?? []) {
    imported = removeTypeDeclaration(imported, omitted, config.domainLabel);
  }
  for (const omitted of config.omitTypes ?? []) {
    if (new RegExp(`\\b${omitted}\\b`, "u").test(imported)) {
      throw new Error(`${config.domainLabel} cannot omit still-referenced generated type ${omitted}`);
    }
  }
  return imported.replace(/\n+$/u, "\n");
}

function generate(config) {
  const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), config.temporaryPrefix));
  const rawPath = path.join(temporaryDirectory, `${config.fileStem}.raw.ts`);
  try {
    execFileSync(
      "cargo",
      [
        "test",
        "-p",
        "rho-desktop",
        config.testFilter,
        "--locked",
        "--",
        "--ignored",
      ],
      {
        cwd: repositoryRoot,
        env: { ...process.env, [config.outputEnvironment]: rawPath },
        stdio: ["ignore", "inherit", "inherit"],
      },
    );
    return transform(fs.readFileSync(rawPath, "utf8"), config);
  } finally {
    fs.rmSync(temporaryDirectory, { recursive: true, force: true });
  }
}

export function runTauriSpectaBindingGenerator(config) {
  const requestedOutput = option("--output");
  const defaultOutput = path.join(repositoryRoot, config.defaultOutput);
  const outputPath = requestedOutput == null
    ? defaultOutput
    : path.resolve(process.cwd(), requestedOutput);
  const generated = generate(config);

  if (process.argv.includes("--check")) {
    if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== generated) {
      throw new Error(`${config.domainLabel} bindings are stale: ${path.relative(repositoryRoot, outputPath)}`);
    }
    console.log(`${config.domainLabel} bindings are current: ${path.relative(repositoryRoot, outputPath)}`);
    return;
  }
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, generated);
  console.log(`Generated ${path.relative(repositoryRoot, outputPath)}`);
}
