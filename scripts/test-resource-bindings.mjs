import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generator = path.join(repositoryRoot, "scripts/generate-resource-bindings.mjs");
const generatedPath = path.join(repositoryRoot, "desktop/ui/src/transport/generated/resource.ts");
const commandNames = [
  "resource_list",
  "resource_resolve",
  "resource_read",
  "resource_update_draft",
  "resource_save",
  "resource_reload",
  "resource_rename",
  "resource_delete",
];

function count(text, needle) {
  return text.split(needle).length - 1;
}

function generate(outputPath, check = false) {
  const args = [generator, "--output", outputPath];
  if (check) args.push("--check");
  execFileSync(process.execPath, args, {
    cwd: repositoryRoot,
    stdio: ["ignore", "ignore", "pipe"],
  });
}

const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "rho-resource-bindings-test-"));
try {
  const first = path.join(temporaryDirectory, "first.ts");
  const second = path.join(temporaryDirectory, "second.ts");
  generate(first);
  generate(second);
  const firstBytes = fs.readFileSync(first);
  assert.deepEqual(firstBytes, fs.readFileSync(second), "two clean Resource generations differ");
  assert.deepEqual(firstBytes, fs.readFileSync(generatedPath), "checked-in Resource bindings are stale");

  fs.appendFileSync(first, "// stale fixture\n");
  assert.throws(
    () => generate(first, true),
    /Command failed/,
    "a one-byte Resource binding drift must fail freshness validation",
  );

  const generated = fs.readFileSync(generatedPath, "utf8");
  const surfaceGenerated = fs.readFileSync(
    path.join(repositoryRoot, "desktop/ui/src/transport/generated/surface-studio.ts"),
    "utf8",
  );
  const tauri = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/tauri.ts"), "utf8");
  const types = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/types.ts"), "utf8");
  const facet = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/resource.ts"), "utf8");
  const mock = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/mock.ts"), "utf8");

  assert.match(generated, /Generated by tauri-specta 2\.0\.0-rc\.25 with specta-typescript 0\.0\.12/);
  assert.match(generated, /Rust sources: rho-ui-contract\/resource \+ rho-desktop\/resource_registry/);
  assert.match(facet, /export interface ResourceTransport/);
  assert.match(facet, /createTauriResourceTransport/);
  assert.match(facet, /unsupported contract version/);
  assert.match(tauri, /\.\.\.createTauriResourceTransport\(invoke\)/);
  assert.match(generated, /export type ResourceBindingV1\b/);
  assert.match(surfaceGenerated, /import type \{ ResourceBindingV1 \} from "\.\/resource"/);
  assert.doesNotMatch(surfaceGenerated, /export type ResourceBindingV1 =/);

  for (const command of commandNames) {
    assert.equal(count(generated, `"${command}"`), 1, `${command} must be generated exactly once`);
    assert.equal(count(tauri, `"${command}"`), 0, `${command} must not remain handwritten`);
  }
  for (const typeName of [
    "ResourceDescriptor",
    "ResourceProviderRegistration",
    "ResourceRegistrySnapshot",
    "ResourceTarget",
    "ResourceResolveRequest",
    "ResourceReadRequest",
    "ResourceContent",
    "ResourceDraftRequest",
    "ResourceSaveRequest",
    "ResourceReloadRequest",
    "ResourceRenameRequest",
    "ResourceDeleteRequest",
  ]) {
    assert.doesNotMatch(
      types,
      new RegExp(`export (?:interface|type) ${typeName}\\b`),
      `${typeName} must not remain a handwritten wire DTO in types.ts`,
    );
  }
  for (const generatedType of [
    "ResourceBindingV1",
    "ResourceDescriptorV1",
    "ResourceRegistrySnapshotV1",
    "ResourceTargetV1",
    "ResourceResolveRequestV1",
    "ResourceReadRequestV1",
    "ResourceContentV1",
    "ResourceDraftRequestV1",
    "ResourceSaveRequestV1",
    "ResourceReloadRequestV1",
    "ResourceRenameRequestV1",
    "ResourceDeleteRequestV1",
  ]) {
    assert.match(generated, new RegExp(`export type ${generatedType}\\b`));
  }
  for (const method of [
    "loadResources",
    "resolveResource",
    "readResource",
    "updateResourceDraft",
    "saveResource",
    "reloadResource",
    "renameResource",
    "deleteResource",
  ]) {
    assert.match(facet, new RegExp(`\\b${method}\\b`));
    assert.match(mock, new RegExp(`\\b${method}\\b`));
  }
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });
}

console.log("Resource generated binding contract passed");
