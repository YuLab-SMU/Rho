import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generator = path.join(repositoryRoot, "scripts/generate-agent-file-bindings.mjs");
const generatedPath = path.join(
  repositoryRoot,
  "desktop/ui/src/transport/generated/agent-file.ts",
);
const commandNames = ["apply_agent_file_edit", "undo_agent_file_edit"];

function count(text, needle) {
  return text.split(needle).length - 1;
}

function generate(outputPath, check = false) {
  const args = [generator, "--output", outputPath];
  if (check) args.push("--check");
  execFileSync(process.execPath, args, {
    cwd: repositoryRoot,
    stdio: ["ignore", "ignore", "pipe"],
  });
}

const temporaryDirectory = fs.mkdtempSync(
  path.join(os.tmpdir(), "rho-agent-file-bindings-test-"),
);
try {
  const first = path.join(temporaryDirectory, "first.ts");
  const second = path.join(temporaryDirectory, "second.ts");
  generate(first);
  generate(second);
  const firstBytes = fs.readFileSync(first);
  assert.deepEqual(firstBytes, fs.readFileSync(second), "two clean Agent file generations differ");
  assert.deepEqual(firstBytes, fs.readFileSync(generatedPath), "checked-in Agent file bindings are stale");

  fs.appendFileSync(first, "// stale fixture\n");
  assert.throws(
    () => generate(first, true),
    /Command failed/,
    "a one-byte Agent file binding drift must fail freshness validation",
  );

  const generated = fs.readFileSync(generatedPath, "utf8");
  const tauri = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/tauri.ts"), "utf8");
  const types = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/types.ts"), "utf8");
  const facet = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/agent-file.ts"), "utf8");
  const mock = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/mock.ts"), "utf8");
  const rust = fs.readFileSync(path.join(repositoryRoot, "desktop/src-tauri/src/main.rs"), "utf8");

  assert.match(generated, /Generated by tauri-specta 2\.0\.0-rc\.25 with specta-typescript 0\.0\.12/);
  assert.match(generated, /Rust sources: rho-desktop\/main Agent file mutation commands/);
  assert.match(generated, /applyAgentFileEdit: \(request: AgentFileApplyRequest\)/);
  assert.match(generated, /undoAgentFileEdit: \(request: AgentFileUndoRequest\)/);
  assert.match(generated, /proposalEventId: number/);
  assert.match(generated, /expectedDiskSha256: string \| null/);
  assert.match(generated, /expectedAfterSha256: string/);
  assert.match(generated, /afterSha256: string \| null/);
  assert.match(generated, /project: AgentFileProjectStateWire/);
  assert.match(generated, /workspace: AgentFileWorkspaceIdentityWire/);
  assert.match(generated, /size_bytes: number/);
  assert.match(generated, /project_revision: number/);
  assert.match(facet, /export interface AgentFileTransport/);
  assert.match(facet, /after_sha256: AgentFileMutationResponseWire\["afterSha256"\]/);
  assert.match(facet, /const \{ afterSha256, \.\.\.rest \} = response/);
  assert.match(tauri, /\.\.\.createTauriAgentFileTransport\(invoke\)/);
  assert.match(mock, /workspace_id: `workspace:\$\{current\.project\.project_id\}`/);

  for (const command of commandNames) {
    assert.equal(count(generated, `"${command}"`), 1, `${command} must be generated exactly once`);
    assert.equal(count(tauri, `"${command}"`), 0, `${command} must not remain handwritten`);
  }
  for (const typeName of [
    "AgentFileApplyRequest",
    "AgentFileUndoRequest",
    "AgentFileMutationResponse",
  ]) {
    assert.doesNotMatch(
      types,
      new RegExp(`export (?:interface|type) ${typeName}\\b`),
      `${typeName} must not remain a handwritten wire DTO in types.ts`,
    );
    assert.match(facet, new RegExp(`export type ${typeName}\\b`));
  }
  for (const method of ["applyAgentFileEdit", "undoAgentFileEdit"]) {
    assert.match(facet, new RegExp(`\\b${method}\\b`));
    assert.match(mock, new RegExp(`\\b${method}\\b`));
  }
  assert.match(rust, /async fn apply_agent_file_edit\([\s\S]{0,300}?\) -> Result<AgentFileMutationResponse, String>/);
  assert.match(rust, /async fn undo_agent_file_edit\([\s\S]{0,300}?\) -> Result<AgentFileMutationResponse, String>/);
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });
}

console.log("Agent file mutation generated binding contract passed");
