#!/usr/bin/env node
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const scriptsRoot = path.join(root, "scripts");
const mode = process.argv[2] ?? "--full";
if (!new Set(["--static", "--full"]).has(mode)) {
  throw new Error("usage: node scripts/test-generated-bindings.mjs [--static|--full]");
}

const generators = fs.readdirSync(scriptsRoot)
  .filter((name) => /^generate-.+-bindings\.mjs$/u.test(name))
  .sort();
const domains = generators.map((name) => name
  .replace(/^generate-/u, "")
  .replace(/-bindings\.mjs$/u, ""));
assert.ok(domains.length > 0, "no generated binding domains found");

const outputs = new Set();
for (const domain of domains) {
  const generatorPath = path.join(scriptsRoot, `generate-${domain}-bindings.mjs`);
  const contractPath = path.join(scriptsRoot, `test-${domain}-bindings.mjs`);
  assert.ok(fs.existsSync(contractPath), `missing focused binding contract: ${path.relative(root, contractPath)}`);
  const generator = fs.readFileSync(generatorPath, "utf8");
  const outputMatch = /defaultOutput:\s*["']([^"']+)["']/u.exec(generator);
  assert.ok(outputMatch, `generator does not declare defaultOutput: ${path.relative(root, generatorPath)}`);
  const output = outputMatch[1];
  assert.ok(!outputs.has(output), `two binding generators own ${output}`);
  outputs.add(output);
  const generatedPath = path.join(root, output);
  assert.ok(fs.existsSync(generatedPath), `missing checked-in generated binding: ${output}`);
  const generated = fs.readFileSync(generatedPath, "utf8");
  assert.match(generated, /Generated by tauri-specta/u, `${output} lost its generated provenance header`);
  assert.doesNotMatch(generated, /stale fixture/u, `${output} contains a stale-test marker`);
}

const generatedDirectory = path.join(root, "desktop/ui/src/transport/generated");
const generatedInventory = fs.readdirSync(generatedDirectory)
  .filter((name) => name.endsWith(".ts"))
  .map((name) => `desktop/ui/src/transport/generated/${name}`)
  .sort();
assert.deepEqual(
  [...outputs].sort(),
  generatedInventory,
  "binding generators and checked-in generated facets must have one-to-one ownership",
);

if (mode === "--static") {
  console.log(`Generated binding static inventory passed: ${domains.length} domains`);
  process.exit(0);
}

const started = Date.now();
for (const domain of domains) {
  const script = path.join(scriptsRoot, `test-${domain}-bindings.mjs`);
  const result = spawnSync(process.execPath, [script], {
    cwd: root,
    encoding: "utf8",
    stdio: "inherit",
  });
  if (result.error != null) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}
console.log(
  `Generated binding full contract passed: ${domains.length} domains in ${((Date.now() - started) / 1000).toFixed(1)}s`,
);
