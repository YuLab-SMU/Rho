import { readFile, writeFile } from 'node:fs/promises';
import { compile } from 'json-schema-to-typescript';

// The public method map is derived from the served contract, not restated. Each
// operation's input and output are compiled from the same JSON Schema the service
// validates with, so a client that names a method, a field or a return type the
// contract does not accept fails to compile instead of failing at runtime.
//
// Ajv remains the runtime authority; these types describe exactly the schemas it
// compiles (`protocol/operations/<method>.json`).
const root = new URL('../', import.meta.url);
const index = JSON.parse(await readFile(new URL('protocol/index.json', root), 'utf8'));
const shared = JSON.parse(await readFile(new URL('protocol/' + index.shared.path, root), 'utf8'));

const pascal = method => method.split('.').map(part => part.replace(/[^A-Za-z0-9]+/g, ' ').trim().split(/\s+/).map(word => word[0].toUpperCase() + word.slice(1)).join('')).join('');
const identifier = name => /^[A-Za-z_$]/.test(name) ? name : '_' + name;

// A schema that allows any additional field says "this payload is open". That is a
// runtime fact and Ajv enforces it; expressing it as a `[k: string]: unknown` index
// signature would also reject every ordinary application object, so the generated
// type lists the declared fields instead. Typed maps (`additionalProperties` with a
// schema, such as a vocabulary) keep their index signature: those are real maps.
const declaredFieldsOnly = value => {
  if (Array.isArray(value)) return value.map(declaredFieldsOnly);
  if (!value || typeof value !== 'object') return value;
  const out = {};
  for (const [key, inner] of Object.entries(value)) {
    // A payload with declared fields keeps those fields; an open bag with none stays a
    // map of unknown values, which is what a caller actually needs to index.
    if (key === 'additionalProperties' && inner === true && value.properties && Object.keys(value.properties).length > 0) continue;
    out[key] = declaredFieldsOnly(inner);
  }
  return out;
};

async function compileSchema(schema, name) {
  // `ignoreMinAndMaxItems` keeps arrays as arrays: the runtime enforces minItems and
  // maxItems, while a generated tuple would make ordinary arrays unassignable for no
  // safety gain. Everything else (required, enums, const, additionalProperties,
  // oneOf/anyOf, dependencies) keeps its published meaning.
  return await compile(declaredFieldsOnly(schema), name, {
    bannerComment: '',
    style: { singleQuote: true, semi: true, tabWidth: 2 },
    ignoreMinAndMaxItems: true,
    enableConstEnums: false,
    // Declared fields only. The published schemas allow additive fields in many
    // replies; enforcing that openness at compile time would make every ordinary
    // application object unassignable, so it stays where it belongs: Ajv validates
    // the real schema, including whether additional fields are allowed.
    additionalProperties: false,
    unknownAny: true,
    declareExternallyReferenced: true,
    strictIndexSignatures: false,
    format: true,
    cwd: new URL('protocol/', root).pathname
  });
}

const blocks = [];
const entries = [];
const names = new Set();
for (const method of Object.keys(index.operations).sort()) {
  const file = JSON.parse(await readFile(new URL('protocol/' + index.operations[method].path, root), 'utf8'));
  if (!file.inputSchema) throw new Error('Missing inputSchema for ' + method);
  if (!file.outputSchema) throw new Error('Missing outputSchema for ' + method);
  const inputName = pascal(method) + 'Input', outputName = pascal(method) + 'Output';
  for (const name of [inputName, outputName]) if (names.has(name)) throw new Error('Duplicate generated type name: ' + name);
  names.add(inputName); names.add(outputName);
  blocks.push(await compileSchema(file.inputSchema, inputName));
  blocks.push(await compileSchema(file.outputSchema, outputName));
  entries.push(`  ${JSON.stringify(method)}: { input: ${inputName}; output: ${outputName} };`);
}

const errorBlock = await compileSchema(shared.definitions.error, 'RhoOperationError');
const eventBlock = await compileSchema({ type: 'object', additionalProperties: true, properties: shared.definitions.event.properties, required: shared.definitions.event.required }, 'RhoEvent');

const header = `// Generated by scripts/contract-types.mjs from the served contract in protocol/.
// Do not edit: run \`npm run build:contracts\` (or \`npm run check:contracts\` to verify).
//
// One entry per public operation: the method name, its accepted input, and the
// value an accepted response carries. The service, the Node client and the browser
// client are all written against these types; runtime validation stays with Ajv.
//
// Contract identity: apiVersion ${index.apiVersion}, schemaVersion ${index.schemaVersion}, ${Object.keys(index.operations).length} operations.
`;

const map = `
/** Every public operation, its accepted input and its response value. */
export interface RhoOperations {
${entries.join('\n')}
}

export type RhoMethod = keyof RhoOperations;
export type RhoInput<M extends RhoMethod> = RhoOperations[M]['input'];
export type RhoOutput<M extends RhoMethod> = RhoOperations[M]['output'];

/** The names a caller may pass to protocol.describe / protocol.validate. */
export const rhoMethods = ${JSON.stringify(Object.keys(index.operations).sort())} as const satisfies readonly RhoMethod[];
export type RhoInputFor<M extends RhoMethod> = RhoOperations[M]['input'];
`;

const text = header + errorBlock + '\n' + eventBlock + '\n' + blocks.join('\n') + map;
if (process.argv.includes('--check')) {
  const current = await readFile(new URL('src/contract.generated.ts', root), 'utf8').catch(() => '');
  if (current !== text) {
    console.error('src/contract.generated.ts is out of date with the served contract. Run: npm run build:contracts');
    process.exitCode = 1;
  } else console.log('Generated contract types are current (' + Object.keys(index.operations).length + ' operations).');
} else {
  await writeFile(new URL('src/contract.generated.ts', root), text);
  console.log('Generated contract types: ' + Object.keys(index.operations).length + ' operations, ' + text.length + ' bytes');
}
