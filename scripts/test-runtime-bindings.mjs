import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generator = path.join(repositoryRoot, "scripts/generate-runtime-bindings.mjs");
const generatedPath = path.join(repositoryRoot, "desktop/ui/src/transport/generated/runtime.ts");
const commandNames = [
  "runtime_list",
  "runtime_create",
  "runtime_interrupt",
  "runtime_restart",
  "runtime_stop",
  "runtime_execution_start",
];

function count(text, needle) {
  return text.split(needle).length - 1;
}

function generate(outputPath, check = false) {
  const args = [generator, "--output", outputPath];
  if (check) args.push("--check");
  execFileSync(process.execPath, args, {
    cwd: repositoryRoot,
    stdio: ["ignore", "ignore", "pipe"],
  });
}

const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "rho-runtime-bindings-test-"));
try {
  const first = path.join(temporaryDirectory, "first.ts");
  const second = path.join(temporaryDirectory, "second.ts");
  generate(first);
  generate(second);
  const firstBytes = fs.readFileSync(first);
  assert.deepEqual(firstBytes, fs.readFileSync(second), "two clean Runtime generations differ");
  assert.deepEqual(firstBytes, fs.readFileSync(generatedPath), "checked-in Runtime bindings are stale");

  fs.appendFileSync(first, "// stale fixture\n");
  assert.throws(
    () => generate(first, true),
    /Command failed/,
    "a one-byte Runtime binding drift must fail freshness validation",
  );

  const generated = fs.readFileSync(generatedPath, "utf8");
  const surfaceGenerated = fs.readFileSync(
    path.join(repositoryRoot, "desktop/ui/src/transport/generated/surface-studio.ts"),
    "utf8",
  );
  const tauri = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/tauri.ts"), "utf8");
  const types = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/types.ts"), "utf8");
  const facet = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/runtime.ts"), "utf8");
  const mock = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/mock.ts"), "utf8");

  assert.match(generated, /Generated by tauri-specta 2\.0\.0-rc\.25 with specta-typescript 0\.0\.12/);
  assert.match(generated, /Rust sources: rho-ui-contract\/runtime \+ rho-desktop\/runtime_registry/);
  assert.match(generated, /import type \{ RuntimeExecution \} from "\.\/runtime-output"/);
  assert.doesNotMatch(generated, /export type RuntimeExecution =/);
  assert.doesNotMatch(generated, /RuntimeExecuteRequestV1_Serialize/);
  assert.match(facet, /export interface RuntimeTransport/);
  assert.match(facet, /createTauriRuntimeTransport/);
  assert.match(facet, /unsupported contract version/);
  assert.match(tauri, /\.\.\.createTauriRuntimeTransport\(invoke\)/);
  for (const command of commandNames) {
    assert.equal(count(generated, `"${command}"`), 1, `${command} must be generated exactly once`);
    assert.equal(count(tauri, `"${command}"`), 0, `${command} must not remain handwritten in tauri.ts`);
  }
  for (const surfaceCommand of ["runtime_attach", "runtime_detach"]) {
    assert.equal(count(generated, `"${surfaceCommand}"`), 0, `${surfaceCommand} belongs to Surface IPC`);
    assert.equal(count(tauri, `"${surfaceCommand}"`), 0, `${surfaceCommand} must not remain handwritten`);
    assert.equal(
      count(surfaceGenerated, `"${surfaceCommand}"`),
      1,
      `${surfaceCommand} must be generated exactly once by Surface IPC`,
    );
  }
  for (const typeName of [
    "RuntimeBinding",
    "RuntimeDescriptor",
    "RuntimeProviderRegistration",
    "RuntimeRegistrySnapshot",
    "RuntimeCreateRequest",
    "RuntimeInstanceRequest",
    "RuntimeExecuteRequest",
    "RuntimeExecutionSourceContext",
    "RuntimeExecutionStartResponse",
  ]) {
    assert.doesNotMatch(
      types,
      new RegExp(`export (?:interface|type) ${typeName}\\b`),
      `${typeName} must not remain a handwritten wire DTO in types.ts`,
    );
  }
  for (const generatedType of [
    "RuntimeBindingV1",
    "RuntimeDescriptorV1",
    "RuntimeRegistrySnapshotV1",
    "RuntimeCreateRequestV1",
    "RuntimeInstanceRequestV1",
    "RuntimeExecuteRequestV1_Deserialize",
    "RuntimeExecutionStartResponse",
  ]) {
    assert.match(generated, new RegExp(`export type ${generatedType}\\b`));
  }
  for (const method of [
    "loadRuntimes",
    "createRuntime",
    "interruptRuntime",
    "restartRuntime",
    "stopRuntime",
    "startRuntimeExecution",
  ]) {
    assert.match(facet, new RegExp(`\\b${method}\\b`));
    assert.match(mock, new RegExp(`\\b${method}\\b`));
  }
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });
}

console.log("Runtime generated binding contract passed");
