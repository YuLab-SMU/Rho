import assert from 'node:assert/strict';
import path from 'node:path';

export async function testHandoffRenderer(page, frame, expect, output) {
  const select=frame.getByRole('combobox',{name:'Select task'}), input=frame.getByRole('textbox',{name:'Agent message'});
  await select.selectOption('native:task-0');await expect(input).toBeEnabled();
  await page.evaluate(()=>window.fixture.handoffContext());
  await expect(frame.locator('#selected-context')).toContainText('Editor documents · 分析 Ω.R');
  const initial=await page.evaluate(()=>window.fixture.snapshot());
  const sends=value=>value.calls.filter(call=>call.arguments?.arguments?.command?.kind==='send'||call.capability?.id==='agent.model.run').length;
  const appends=value=>value.calls.filter(call=>call.capability?.id==='agent.handoff.append');
  await frame.getByRole('button',{name:'Task actions'}).click();
  await frame.getByRole('button',{name:'Prepare handoff',exact:true}).click();
  const panel=frame.getByRole('region',{name:'Prepare handoff'}), editor=panel.getByRole('textbox',{name:'Handoff draft'});
  await expect(panel).toBeVisible();await expect(editor).toContainText('');
  await expect(panel.getByRole('combobox',{name:'Send context to'})).toBeEnabled();
  await panel.getByRole('combobox',{name:'Send context to'}).selectOption('native:task-1');
  await expect(panel.getByRole('button',{name:'Add to draft',exact:true})).toBeEnabled();
  const body='Goal:\n继续核对原始分析 Ω\n\nConfirmed:\nReviewed original source.\n\nNext:\nRead the saved result before sending.';
  await editor.dispatchEvent('compositionstart');await editor.fill(body);
  await editor.dispatchEvent('keydown',{key:'Enter',code:'Enter',keyCode:229,isComposing:true});
  await expect(select).toBeDisabled();await expect(panel.getByRole('button',{name:'Add to draft',exact:true})).toBeDisabled();
  assert.equal(appends(await page.evaluate(()=>window.fixture.snapshot())).length,0);
  await editor.dispatchEvent('compositionend');await expect(select).toBeEnabled();
  await expect.poll(async()=>(await page.evaluate(()=>window.fixture.snapshot())).view.state.handoffs.editors['native:task-0'].body).toBe(body);
  await page.evaluate(()=>window.fixture.contextFault('changed'));
  await panel.getByRole('button',{name:'Editor documents · 分析 Ω.R',exact:true}).click();
  await expect(panel.locator('#handoff-preview')).toContainText('Source changed');
  await panel.getByRole('button',{name:'Close handoff source preview'}).click();
  await page.evaluate(()=>window.fixture.contextFault(''));
  await panel.getByRole('button',{name:'Remove Editor documents · 分析 Ω.R from handoff'}).click();
  await panel.getByRole('button',{name:'Refresh source and target'}).click();
  await expect(panel.getByRole('button',{name:'Add to draft',exact:true})).toBeEnabled();
  await expect(editor).toHaveValue(body);await expect(panel.locator('#handoff-sources')).toBeEmpty();
  await page.evaluate(()=>window.fixture.changeHandoffTarget());
  await panel.getByRole('button',{name:'Add to draft',exact:true}).click();
  await expect(panel.locator('#handoff-error')).toContainText('target draft changed');
  await expect(panel.locator('#handoff-existing-text')).toHaveText('Changed target draft · 保留');
  assert.equal(appends(await page.evaluate(()=>window.fixture.snapshot())).length,0);
  for(const width of [960,440,220]){
    await page.setViewportSize({width,height:820});
    assert.equal(await panel.evaluate(node=>node.scrollWidth>node.clientWidth),false,`Handoff panel overflow at ${width}`);
    assert.equal(await frame.locator('body').evaluate(node=>node.scrollWidth>innerWidth),false);
    await page.screenshot({path:path.join(output,`agent-handoff-${width}.png`)});
  }
  await page.setViewportSize({width:320,height:400});await panel.getByRole('button',{name:'Add to draft',exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(output,'agent-handoff-short.png')});
  await page.setViewportSize({width:440,height:820});
  await page.evaluate(()=>window.fixture.loseHandoffReply());
  await panel.getByRole('button',{name:'Add to draft',exact:true}).click();await expect(panel.locator('#handoff-error')).toContainText('Lost handoff reply');
  let snapshot=await page.evaluate(()=>window.fixture.snapshot());const original=appends(snapshot)[0];assert.ok(original);
  await page.evaluate(()=>window.fixture.reload());await expect(panel.getByRole('button',{name:'Check receipt',exact:true})).toBeEnabled();
  await expect(editor).toHaveValue(body);await expect(editor).toHaveAttribute('readonly','');
  snapshot=await page.evaluate(()=>window.fixture.snapshot());assert.equal(appends(snapshot).length,1);assert.equal(sends(snapshot),sends(initial));
  await panel.getByRole('button',{name:'Check receipt',exact:true}).click();await expect(panel.locator('#handoff-confirmed')).toBeVisible();
  await expect(panel.locator('#handoff-task-note')).toBeEmpty();
  await expect(panel.getByRole('combobox',{name:'Send context to'}).locator('option:checked')).toHaveText('Compare the saved analysis');
  await page.screenshot({path:path.join(output,'agent-handoff-recovered.png')});
  await panel.getByRole('button',{name:'Open target draft',exact:true}).click();await expect(input).toHaveValue('Changed target draft · 保留\n\n'+body);
  snapshot=await page.evaluate(()=>window.fixture.snapshot());assert.equal(appends(snapshot).length,1);assert.equal(sends(snapshot),sends(initial));
  // The same ordinary view transfers into a Rho draft, still without Send.
  const rhoId=snapshot.rhoTasks[0][0], previous=snapshot.rhoTasks[0][1].draft_content.text;
  await frame.getByRole('button',{name:'Task actions'}).click();await frame.getByRole('button',{name:'Prepare handoff',exact:true}).click();
  await expect(panel.getByRole('combobox',{name:'Send context to'})).toBeEnabled();
  await panel.getByRole('combobox',{name:'Send context to'}).selectOption(`rho:${rhoId}`);
  await expect(panel.getByRole('button',{name:'Add to draft',exact:true})).toBeEnabled();await editor.fill('Goal:\nContinue in the existing Rho task.');
  await panel.getByRole('button',{name:'Add to draft',exact:true}).click();await expect(panel.locator('#handoff-confirmed')).toBeVisible();
  await panel.getByRole('button',{name:'Open target draft',exact:true}).click();
  await expect(input).toHaveValue((previous?previous+'\n\n':'')+'Goal:\nContinue in the existing Rho task.');
  snapshot=await page.evaluate(()=>window.fixture.snapshot());assert.equal(appends(snapshot).length,2);assert.equal(sends(snapshot),sends(initial));
  console.log('Ordinary handoff browser: reviewed text, IME, stale target, reference removal, lost reply/reload and native/Rho draft append passed. Synthetic peer only.');
}
