import assert from 'node:assert/strict';
import path from 'node:path';
export async function testContextRenderer(page, frame, expect, output) {
  const initial = await page.evaluate(()=>window.fixture.snapshot());
  await frame.getByRole('button',{name:'Sent context',exact:true}).click();
  const originalDialog=frame.getByRole('dialog',{name:'Choose context'});
  await expect(originalDialog.locator('#context-captures')).toContainText('original_value <- 7 # 中文 Ω');
  await expect(originalDialog.locator('#context-captures')).toContainText('Original synchronized version 6');
  const read=await page.evaluate(()=>window.fixture.snapshot());
  assert.equal(read.reads['editor.context.preview']??0,initial.reads['editor.context.preview']??0);
  await page.screenshot({path:path.join(output,'agent-context-original.png')});
  await originalDialog.getByRole('button',{name:'Close context'}).click();
  const before = await page.evaluate(()=>window.fixture.snapshot());
  await frame.getByRole('button',{name:'Choose context',exact:true}).click();
  const dialog=frame.getByRole('dialog',{name:'Choose context'});
  await expect(dialog.getByRole('button',{name:/分析 Ω.R/})).toBeEnabled();
  await dialog.getByRole('button',{name:/分析 Ω.R/}).click();
  await expect(dialog.getByRole('combobox',{name:'Context inclusion'})).toBeEnabled();
  await dialog.getByRole('combobox',{name:'Context inclusion'}).selectOption('1');
  await expect(dialog.locator('#context-preview')).toHaveText('selected_value <- 42 # 中文 Ω');
  await expect(dialog.getByRole('button',{name:'Add to draft'})).toBeEnabled();
  for(const width of [960,440,320,220]){
    await page.setViewportSize({width,height:820});
    assert.equal(await dialog.evaluate(node=>node.scrollWidth>node.clientWidth),false,`Context dialog overflow at ${width}`);
    await page.screenshot({path:path.join(output,`agent-context-${width}.png`)});
  }
  await page.setViewportSize({width:320,height:400});
  await dialog.getByRole('button',{name:'Add to draft'}).scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(output,'agent-context-short.png')});
  await dialog.getByRole('button',{name:'Add to draft'}).click();
  await expect(dialog).not.toBeVisible();
  await expect(frame.getByRole('button',{name:'Editor documents · 分析 Ω.R',exact:true})).toBeVisible();
  await expect(frame.getByRole('button',{name:'Send message'})).toBeEnabled();
  await expect.poll(async()=> (await page.evaluate(()=>window.fixture.snapshot())).details[0][1].draft.content.context.length).toBe(1);
  const saved = await page.evaluate(()=>window.fixture.snapshot());
  const original=saved.details[0][1].draft.content.context[0];
  assert.equal(original.reference.selector.version,7);assert.equal(original.inclusion,'{"kind":"selection"}');
  assert.equal(saved.calls.filter(c=>c.arguments?.arguments?.command?.kind==='send').length,before.calls.filter(c=>c.arguments?.arguments?.command?.kind==='send').length);
  await page.evaluate(()=>window.fixture.reload());
  await expect(frame.getByRole('button',{name:'Editor documents · 分析 Ω.R',exact:true})).toBeVisible();
  await page.evaluate(()=>window.fixture.contextFault('changed'));
  await frame.getByRole('button',{name:'Editor documents · 分析 Ω.R',exact:true}).click();
  await expect(dialog.getByRole('alert')).toContainText('Source changed');
  await expect(dialog.getByRole('button',{name:'Add to draft'})).not.toBeVisible();
  await dialog.getByRole('button',{name:'Close context'}).click();
  const retained=await page.evaluate(()=>window.fixture.snapshot());assert.deepEqual(retained.details[0][1].draft.content.context[0],original);
  await frame.getByRole('button',{name:'Remove Editor documents · 分析 Ω.R from draft'}).click();
  await expect.poll(async()=> (await page.evaluate(()=>window.fixture.snapshot())).details[0][1].draft.content.context.length).toBe(0);
  await page.evaluate(()=>window.fixture.contextFault('truncated'));
  await frame.getByRole('button',{name:'Choose context',exact:true}).click();
  await dialog.getByRole('button',{name:/分析 Ω.R/}).click();
  await expect(dialog.locator('#context-preview-note')).toContainText('Partial preview');
  await expect(dialog.getByRole('button',{name:'Add to draft'})).toBeDisabled();
  await dialog.getByRole('button',{name:'Close context'}).click();
  await page.evaluate(()=>window.fixture.contextFault(''));
  await page.setViewportSize({width:440,height:820});
  console.log('Ordinary context browser: selection, bounded text preview, draft persistence/reload, changed/partial sources and responsive dialog passed. Synthetic Editor peer only.');
}
