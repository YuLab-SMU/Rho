import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generator = path.join(repositoryRoot, "scripts/generate-agent-conversation-bindings.mjs");
const generatedPath = path.join(
  repositoryRoot,
  "desktop/ui/src/transport/generated/agent-conversation.ts",
);
const commandNames = [
  "list_agent_conversations",
  "create_agent_conversation",
  "list_agent_turns",
];

function count(text, needle) {
  return text.split(needle).length - 1;
}

function generate(outputPath, check = false) {
  const args = [generator, "--output", outputPath];
  if (check) args.push("--check");
  execFileSync(process.execPath, args, {
    cwd: repositoryRoot,
    stdio: ["ignore", "ignore", "pipe"],
  });
}

const temporaryDirectory = fs.mkdtempSync(
  path.join(os.tmpdir(), "rho-agent-conversation-bindings-test-"),
);
try {
  const first = path.join(temporaryDirectory, "first.ts");
  const second = path.join(temporaryDirectory, "second.ts");
  generate(first);
  generate(second);
  const firstBytes = fs.readFileSync(first);
  assert.deepEqual(
    firstBytes,
    fs.readFileSync(second),
    "two clean Agent conversation generations differ",
  );
  assert.deepEqual(
    firstBytes,
    fs.readFileSync(generatedPath),
    "checked-in Agent conversation bindings are stale",
  );

  fs.appendFileSync(first, "// stale fixture\n");
  assert.throws(
    () => generate(first, true),
    /Command failed/,
    "a one-byte Agent conversation binding drift must fail freshness validation",
  );

  const generated = fs.readFileSync(generatedPath, "utf8");
  const tauri = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/tauri.ts"), "utf8");
  const types = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/types.ts"), "utf8");
  const facet = fs.readFileSync(
    path.join(repositoryRoot, "desktop/ui/src/transport/agent-conversation.ts"),
    "utf8",
  );
  const mock = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/mock.ts"), "utf8");

  assert.match(generated, /Generated by tauri-specta 2\.0\.0-rc\.25 with specta-typescript 0\.0\.12/);
  assert.match(generated, /Rust sources: rho-store\/agent \+ rho-desktop commands\/agent_conversation facade/);
  assert.match(generated, /listAgentTurns: \(conversationId: string \| null, limit: number \| null\)/);
  assert.match(facet, /export interface AgentConversationTransport/);
  assert.match(facet, /createTauriAgentConversationTransport/);
  assert.doesNotMatch(facet, /unsupported mode|"ask" \| "plan" \| "act"/);
  assert.match(tauri, /\.\.\.createTauriAgentConversationTransport\(invoke\)/);

  for (const command of commandNames) {
    assert.equal(count(generated, `"${command}"`), 1, `${command} must be generated exactly once`);
    assert.equal(count(tauri, `"${command}"`), 0, `${command} must not remain handwritten`);
  }
  for (const typeName of ["AgentConversationSummary", "AgentTurnSummary"]) {
    assert.doesNotMatch(
      types,
      new RegExp(`export (?:interface|type) ${typeName}\\b`),
      `${typeName} must not remain a handwritten wire DTO in types.ts`,
    );
    assert.match(generated, new RegExp(`export type ${typeName}\\b`));
  }
  for (const method of [
    "listAgentConversations",
    "createAgentConversation",
    "listAgentTurns",
  ]) {
    assert.match(facet, new RegExp(`\\b${method}\\b`));
    assert.match(mock, new RegExp(`\\b${method}\\b`));
  }
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });
}

console.log("Agent conversation generated binding contract passed");
