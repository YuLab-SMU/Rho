import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generator = path.join(repositoryRoot, "scripts/generate-agent-runtime-bindings.mjs");
const generatedPath = path.join(
  repositoryRoot,
  "desktop/ui/src/transport/generated/agent-runtime.ts",
);
const commandNames = ["agent_runtime_status", "agent_runtime_retry"];

function count(text, needle) {
  return text.split(needle).length - 1;
}

function generate(outputPath, check = false) {
  const args = [generator, "--output", outputPath];
  if (check) args.push("--check");
  execFileSync(process.execPath, args, {
    cwd: repositoryRoot,
    stdio: ["ignore", "ignore", "pipe"],
  });
}

const temporaryDirectory = fs.mkdtempSync(
  path.join(os.tmpdir(), "rho-agent-runtime-bindings-test-"),
);
try {
  const first = path.join(temporaryDirectory, "first.ts");
  const second = path.join(temporaryDirectory, "second.ts");
  generate(first);
  generate(second);
  const firstBytes = fs.readFileSync(first);
  assert.deepEqual(
    firstBytes,
    fs.readFileSync(second),
    "two clean Agent runtime generations differ",
  );
  assert.deepEqual(
    firstBytes,
    fs.readFileSync(generatedPath),
    "checked-in Agent runtime bindings are stale",
  );

  fs.appendFileSync(first, "// stale fixture\n");
  assert.throws(
    () => generate(first, true),
    /Command failed/,
    "a one-byte Agent runtime binding drift must fail freshness validation",
  );

  const generated = fs.readFileSync(generatedPath, "utf8");
  const tauri = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/tauri.ts"), "utf8");
  const types = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/types.ts"), "utf8");
  const facet = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/agent-runtime.ts"), "utf8");
  const mock = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/mock.ts"), "utf8");
  const rustService = fs.readFileSync(path.join(repositoryRoot, "desktop/src-tauri/src/main.rs"), "utf8");
  const rustFacade = fs.readFileSync(
    path.join(repositoryRoot, "desktop/src-tauri/src/commands/startup.rs"),
    "utf8",
  );

  assert.match(generated, /Generated by tauri-specta 2\.0\.0-rc\.25 with specta-typescript 0\.0\.12/);
  assert.match(generated, /Rust sources: rho-desktop Agent runtime service \+ commands\/startup facade/);
  assert.match(generated, /agentRuntimeStatus: \(\) =>/);
  assert.match(generated, /agentRuntimeRetry: \(\) =>/);
  assert.match(generated, /export type AgentRuntimeStatusView/);
  for (const field of ["status", "rscript", "r_version", "provider_adapters_available", "provider_health", "dependencies"]) {
    assert.match(generated, new RegExp(`\\n\\t${field}:`), `${field} must be required in the response view`);
    assert.doesNotMatch(generated, new RegExp(`\\n\\t${field}\\?:`));
  }
  assert.match(facet, /export interface AgentRuntimeTransport/);
  assert.match(facet, /createTauriAgentRuntimeTransport/);
  assert.match(tauri, /\.\.\.agentRuntimeTransport/);

  for (const command of commandNames) {
    assert.equal(count(generated, `"${command}"`), 1, `${command} must be generated exactly once`);
    assert.equal(count(tauri, `"${command}"`), 0, `${command} must not remain handwritten`);
  }
  for (const typeName of ["AgentDependencyDiagnostics", "AgentRuntimeDiagnostics"]) {
    assert.doesNotMatch(
      types,
      new RegExp(`export (?:interface|type) ${typeName}\\b`),
      `${typeName} must not remain a handwritten wire DTO in types.ts`,
    );
    assert.match(facet, new RegExp(`export type ${typeName}\\b`));
  }
  for (const method of ["getAgentRuntimeDiagnostics", "retryAgentRuntime"]) {
    assert.match(facet, new RegExp(`\\b${method}\\b`));
    assert.match(mock, new RegExp(`\\b${method}\\b`));
  }
  assert.match(
    rustFacade,
    /fn agent_runtime_status\([\s\S]{0,400}?\) -> Result<AgentRuntimeStatusView, String>/,
  );
  assert.match(
    rustFacade,
    /async fn agent_runtime_retry\([\s\S]{0,400}?\) -> Result<AgentRuntimeStatusView, String>/,
  );
  assert.match(rustService, /serde\(default = "default_agent_runtime_status"\)/);
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });
}

console.log("Agent runtime diagnostics generated binding contract passed");
