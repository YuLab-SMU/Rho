import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generator = path.join(repositoryRoot, "scripts/generate-agent-execution-bindings.mjs");
const generatedPath = path.join(
  repositoryRoot,
  "desktop/ui/src/transport/generated/agent-execution.ts",
);
const commandNames = [
  "agent_context_preview",
  "run_agent",
  "retry_agent_turn",
  "cancel_agent_turn",
  "respond_approval",
];

function count(text, needle) {
  return text.split(needle).length - 1;
}

function generate(outputPath, check = false) {
  const args = [generator, "--output", outputPath];
  if (check) args.push("--check");
  execFileSync(process.execPath, args, {
    cwd: repositoryRoot,
    stdio: ["ignore", "ignore", "pipe"],
  });
}

const temporaryDirectory = fs.mkdtempSync(
  path.join(os.tmpdir(), "rho-agent-execution-bindings-test-"),
);
try {
  const first = path.join(temporaryDirectory, "first.ts");
  const second = path.join(temporaryDirectory, "second.ts");
  generate(first);
  generate(second);
  const firstBytes = fs.readFileSync(first);
  assert.deepEqual(
    firstBytes,
    fs.readFileSync(second),
    "two clean Agent execution generations differ",
  );
  assert.deepEqual(
    firstBytes,
    fs.readFileSync(generatedPath),
    "checked-in Agent execution bindings are stale",
  );

  fs.appendFileSync(first, "// stale fixture\n");
  assert.throws(
    () => generate(first, true),
    /Command failed/,
    "a one-byte Agent execution binding drift must fail freshness validation",
  );

  const generated = fs.readFileSync(generatedPath, "utf8");
  const tauri = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/tauri.ts"), "utf8");
  const types = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/types.ts"), "utf8");
  const facet = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/agent-execution.ts"), "utf8");
  const mock = fs.readFileSync(path.join(repositoryRoot, "desktop/ui/src/transport/mock.ts"), "utf8");
  const rust = fs.readFileSync(
    path.join(repositoryRoot, "desktop/src-tauri/src/commands/agent_execution.rs"),
    "utf8",
  );

  assert.match(generated, /Generated by tauri-specta 2\.0\.0-rc\.25 with specta-typescript 0\.0\.12/);
  assert.match(generated, /Rust sources: rho-store\/runtime_output \+ rho-desktop\/commands\/agent_execution/);
  assert.match(generated, /import type \{ RuntimeExecutionStatus, RuntimeOutputReference, RuntimeOutputState \} from "\.\/runtime-output"/);
  assert.match(generated, /runAgent: \(prompt: string, mode: string, taskKind: string \| null/);
  assert.match(generated, /editorContext: AgentJsonValue \| null/);
  assert.match(generated, /contextPlanDigest: string \| null/);
  assert.match(generated, /export type AgentJsonValue = null \| boolean \| number/);
  assert.doesNotMatch(generated, /export type RuntimeOutputReference\b/);
  assert.doesNotMatch(generated, /export type RuntimeExecutionStatus\b/);
  assert.doesNotMatch(generated, /export type RuntimeOutputState\b/);
  assert.match(facet, /export interface AgentExecutionTransport/);
  assert.match(facet, /createTauriAgentExecutionTransport/);
  assert.match(tauri, /\.\.\.createTauriAgentExecutionTransport\(invoke\)/);

  for (const command of commandNames) {
    assert.equal(count(generated, `"${command}"`), 1, `${command} must be generated exactly once`);
    assert.equal(count(tauri, `"${command}"`), 0, `${command} must not remain handwritten`);
  }
  for (const method of [
    "previewAgentContext",
    "runAgent",
    "retryAgentTurn",
    "cancelAgentTurn",
    "respondAgentApproval",
  ]) {
    assert.match(facet, new RegExp(`\\b${method}\\b`));
    assert.match(mock, new RegExp(`\\b${method}\\b`));
  }
  for (const typeName of [
    "AgentContextPreviewRequest",
    "AgentContextPlanPreview",
    "RunAgentRequest",
    "RunAgentResponse",
    "AgentApprovalDecisionRequest",
  ]) {
    assert.doesNotMatch(
      types,
      new RegExp(`export (?:interface|type) ${typeName}\\b`),
      `${typeName} must not remain a handwritten wire DTO in types.ts`,
    );
    assert.match(facet, new RegExp(`export type ${typeName}\\b`));
  }
  for (const responseType of [
    "AgentContextPlanPreviewView",
    "AgentTurnStartResponse",
    "AgentTurnCancelResponse",
    "AgentApprovalDeliveryResponse",
  ]) {
    assert.match(generated, new RegExp(`export type ${responseType}\\b`));
  }
  for (const [command, responseType] of Object.entries({
    agent_context_preview: "AgentContextPlanPreviewView",
    run_agent: "AgentTurnStartResponse",
    retry_agent_turn: "AgentTurnStartResponse",
    cancel_agent_turn: "AgentTurnCancelResponse",
    respond_approval: "AgentApprovalDeliveryResponse",
  })) {
    assert.match(
      rust,
      new RegExp(`async fn ${command}\\([\\s\\S]{0,2000}?\\) -> Result<${responseType}, String>`),
      `${command} must return its typed response instead of serde_json::Value`,
    );
  }
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });
}

console.log("Agent context and turn-control generated binding contract passed");
