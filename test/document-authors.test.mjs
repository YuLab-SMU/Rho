import { test } from 'node:test';
import assert from 'node:assert/strict';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import { RhoService } from '../dist/server.js';
import { BrowserClient } from '../dist/browser.js';
import { CheckedClient } from './checked-client.mjs';
const pluginRequire = createRequire(import.meta.resolve('@rho-workspace/plugin-agent'));
const { Client } = await import(pathToFileURL(pluginRequire.resolve('@modelcontextprotocol/sdk/client/index.js')));
const { StdioClientTransport } = await import(pathToFileURL(pluginRequire.resolve('@modelcontextprotocol/sdk/client/stdio.js')));

test('authenticated HTTP and real stdio MCP share author undo, targeted revert and exact change snapshots', async () => {
  const root = await fs.mkdtemp(path.join(tmpdir(), 'rho-authors-'));
  const config = { root, stateDir: path.join(root, '.service'), coreBinary: '/missing', rscript: '/missing' };
  let service = await new RhoService(config).start();
  const agent = new Client({ name: 'document-author-consumer', version: '1.0' });
  let starts = 0, submits = 0;
  service.bridge.ensureOwnedHost = async () => { starts++; throw new Error('Unexpected Host start'); };
  const native = service.bridge.call.bind(service.bridge);
  service.bridge.call = async (root, method, ...args) => { if (method === 'submit') { submits++; throw new Error('Unexpected native submit'); } return native(root, method, ...args); };
  try {
    let c = new CheckedClient({ url: service.url, token: service.adminToken });
    const p = await c.call('project.create', { name: 'p' });
    const call = (m, input = {}) => c.call(m, { projectId: p.id, ...input });
    let d = await call('document.open', { path: 'notes.md' });
    const grant = await call('session.grant', { externalSessionId: 'actual-agent', methods: ['capability.list', 'document.read', 'document.edit', 'document.undoOwn', 'document.revert', 'document.history', 'document.change.read'] });
    const transport = new StdioClientTransport({ command: process.execPath, args: [fileURLToPath(import.meta.resolve('@rho-workspace/plugin-agent/mcp'))], env: { PATH: process.env.PATH, RHO_AGENT_CONNECTION: grant.connectionFile }, stderr: 'pipe' });
    transport.stderr.resume(); await agent.connect(transport);
    assert.ok((await agent.listTools()).tools.some(t => t.name === 'rho_document_undoOwn'));
    const tool = async (name, input) => {
      const response = await agent.callTool({ name: 'rho_' + name.replaceAll('.', '_'), arguments: input });
      assert.notEqual(response.isError, true, JSON.stringify(response.content));
      return JSON.parse(response.content[0].text).value;
    };
    d = await call('document.edit', { documentId: d.id, expectedVersion: 1, expectedRevision: 0, changeId: 'human', undoGroup: 'human', edits: [{ from: 0, to: 0, insert: 'human 中文\n' }] });
    d = await tool('document.edit', { documentId: d.id, expectedVersion: d.version, expectedRevision: d.revision, changeId: 'agent', undoGroup: 'agent', edits: [{ from: d.content.length, to: d.content.length, insert: 'agent 🧬\n' }] });
    const actualAgent = d.author; assert.notEqual(actualAgent, 'operator');
    const cursor = (await call('observation.snapshot')).cursor;
    const history = await call('document.history', { documentId: d.id });
    assert.equal(history.entries.find(e => e.changeId === 'human').author, 'operator');
    assert.equal(history.entries.find(e => e.changeId === 'agent').author, actualAgent);
    const before = await tool('document.change.read', { documentId: d.id, targetChangeId: 'agent' });
    assert.equal(before.before.content, 'human 中文\n'); assert.equal(before.after.content, d.content);
    assert.equal((await call('observation.snapshot')).cursor, cursor, 'history reads emit no document mutation');
    const own = { projectId: p.id, documentId: d.id, expectedVersion: d.version, expectedRevision: d.revision, changeId: 'human-undo' };
    const sdk = new BrowserClient({ url: service.url, token: service.adminToken }, async (...args) => { const reply = await fetch(...args); await reply.text(); throw new TypeError('lost acknowledgement'); });
    await assert.rejects(sdk.call('document.undoOwn', own), /lost acknowledgement/);
    d = await c.call('document.undoOwn', own);
    assert.equal(d.content, 'agent 🧬\n');
    const forged = await agent.callTool({ name: 'rho_document_undoOwn', arguments: { documentId: d.id, expectedVersion: d.version, expectedRevision: d.revision, changeId: 'forged', author: 'operator' } });
    assert.equal(forged.isError, true);
    d = await tool('document.undoOwn', { documentId: d.id, expectedVersion: d.version, expectedRevision: d.revision, changeId: 'agent-undo' });
    assert.equal(d.content, '');
    // An explicit per-change revert may also reverse a compensation record.
    d = await call('document.revert', { documentId: d.id, expectedVersion: d.version, expectedRevision: d.revision, changeId: 'undo-agent-undo', targetChangeId: 'agent-undo' });
    assert.equal(d.content, 'agent 🧬\n');
    const revert = { documentId: d.id, expectedVersion: d.version, expectedRevision: d.revision, changeId: 'revert-agent', targetChangeId: 'agent' };
    d = await call('document.revert', revert); assert.equal(d.content, '');
    const pairing = await service.browser.createPairing();
    const connection = await BrowserClient.pair(service.url, pairing.code, (url, init) => fetch(url, { ...init, headers: { ...init.headers, origin: service.url } }));
    const browser = new BrowserClient(connection);
    await assert.rejects(browser.call('document.undoOwn', own), e => e.error.kind === 'conflict', 'an operator transaction cannot be replayed as the browser principal');
    service.state.principals.find(p => p.kind === 'browser').methods.push('document.undo');
    await assert.rejects(browser.call('document.undo', { ...own, changeId: 'wrong-keyboard' }), e => e.error.kind === 'unavailable');
    await call('workspace.export', { destination: 'export', format: 3 });
    const q = await c.call('project.create', { name: 'restored' });
    await fs.cp(path.join(p.root, 'export'), path.join(q.root, 'import'), { recursive: true });
    await c.call('workspace.restore', { projectId: q.id, source: 'import' });
    const restored = await c.call('document.change.read', { projectId: q.id, documentId: d.id, targetChangeId: 'agent' });
    assert.equal(restored.change.author, actualAgent); assert.equal(restored.before.content, before.before.content);
    assert.equal(starts, 0); assert.equal(submits, 0);
    await agent.close(); await service.close();
    service = await new RhoService(config).start(); c = new CheckedClient({ url: service.url, token: service.adminToken });
    assert.deepEqual(await call('document.revert', revert), d, 'service restart retains the same revert receipt');
  } finally { await agent.close(); if (service.server.listening) await service.close(); await fs.rm(root, { recursive: true, force: true }); }
});
